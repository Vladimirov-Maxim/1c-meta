SOURCE = os.path.join(ROOT, "tools", "md_design_properties.tsv")
TARGET = os.path.join(ROOT, "meta", "domain", "form_properties.py")

#: (тип, вид) платформы -> слово домена. Слова — те же, что у видов элементов
