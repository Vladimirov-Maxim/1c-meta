#: Строки таблицы, которые не свойства, а служебные колонки Накидки.
SKIP = {"Тип", "Имя", "Путь"}

#: Чего в справочнике нет, а в платформе и в корпусе есть. Замер по реальной
#: выгрузке: группировка `Horizontal` стоит у 21 892 групп из 60 331.
ENUM_ADDITIONS = {
    "ГруппировкаПодчиненныхЭлементовФормы": {"Горизонтальная": "Horizontal"},
}


#: Поправки к справочнику: (английское имя свойства, тип в справочнике) ->
#: верный тип. У девятнадцати видов полей тип подсказки в таблице сдвинут со
#: строки «СочетаниеКлавиш» выше — «Сочетание клавиш» вместо «Строка», и без
#: поправки подсказку нельзя было бы задать ни флажку, ни переключателю, ни
#: надписи. У поля ввода и групп — «Строка».
TYPE_CORRECTIONS = {
    ("ToolTip", "Сочетание клавиш"): "Строка",
}


def read_rows():
    with open(SOURCE, encoding="utf-8") as source:
        lines = [line for line in source.read().split("\n") if line.strip()]
    header = lines[0].split("\t")
    return [dict(zip(header, line.split("\t"), strict=False)) for line in lines[1:]]


def build(rows):
    properties = {}
    enums = {}
    for row in rows:
        kind = KINDS.get((row["Тип"], row["Вид"]))
        if kind is None or row["Имя"] in SKIP or not row["ИмяАнгл"]:
            continue
        values = {}
        for index in range(1, 21):
            russian = row.get(f"Значение{index}")
            english = row.get(f"ЗначениеАнгл{index}")
            if russian and english:
                values[russian] = english
        value_kind = row["ТипЗначения"]
        value_kind = TYPE_CORRECTIONS.get((row["ИмяАнгл"], value_kind), value_kind)
        if values:
            known = enums.setdefault(value_kind, {})
            for russian, english in values.items():
                known.setdefault(russian, english)
        properties.setdefault(kind, {})[row["Имя"]] = (
            row["ИмяАнгл"], value_kind, row["ЗначениеПоУмолчанию"] or None)
    for value_kind, values in ENUM_ADDITIONS.items():
        enums.setdefault(value_kind, {}).update(values)
    return properties, enums


def render(properties, enums):
    out = ['"""Свойства элементов формы: имена, типы значений, умолчания.',
           "",
           "Сгенерировано `tools/form_properties_from_md_design.py` из справочника",
           "проекта «Накидка» (crimsongoldteam/md_design, MIT, © 2025 Zherebtsov",
           "Nikita; текст лицензии — `THIRD_PARTY_NOTICES.md`) — не править руками,",
           "перегенерировать. Совпадение с таблицей проверяет тест.",
           "",
           "Это платформенные факты — так свойства зовёт синтакс-помощник и так их",
           "называет разработчик в задании. Как свойство пишется в файле конкретной",
           "версии выгрузки, домен не знает: реализация формата переводит английское",
           "имя в тег (у 2.21 они совпадают, кроме десятка отклонений).",
           "",
           "`PROPERTIES[вид][русское имя] = (английское имя, вид значения, умолчание)`",
           "`ENUMS[вид значения] = {русское значение: английское}`",
           '"""',
           "",
           "PROPERTIES = {"]
    for kind in properties:
        out.append(f'    "{kind}": {{')
        for name, (english, value_kind, default) in properties[kind].items():
            out.append(f'        "{name}": ({english!r}, {value_kind!r}, {default!r}),')
        out.append("    },")
    out.append("}")
    out.append("")
    out.append("ENUMS = {")
    for value_kind, values in enums.items():
        out.append(f'    "{value_kind}": {{')
        for russian, english in values.items():
            out.append(f'        "{russian}": {english!r},')
        out.append("    },")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    properties, enums = build(read_rows())
    text = render(properties, enums)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as target:
        target.write(text)
    print(f"видов {len(properties)}, свойств {sum(len(v) for v in properties.values())}, "
          f"перечислений {len(enums)} -> {TARGET}")


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    main()
