"""Символы, которых не должно быть в тексте модуля BSL.

Два перечня с разными основаниями: символы, которые bsl-ls считает ошибкой, и
кавычки-ёлочки: в коде кавычки прямые.

Первый перечень — ровно тот, по которому bsl-ls выдаёт ошибку InvalidCharacterInFile
(bsl-language-server 0.29.0, шаблон `[\\u00AD\\u2012-\\u2015\\u2212]|\\u00A0`,
снят с самой диагностики); основание — стандарт «Тексты модулей» (#std456).
Дефис вместо длинного тире нужен и в комментариях, и в литералах: инструмент
сам пишет код (описание процедуры доработки формы), и проверять надо и его.
"""

#: Символ -> (как называется, что сделать). Ключи — кодами: невидимые символы
#: при правке файла редактором легко потерять (неразрывный пробел превращается в обычный).
INVALID = {
    "\u00ad": ("мягкий перенос", "уберите его"),
    "\u2012": ("цифровое тире", "замените на «-»"),
    "\u2013": ("среднее тире", "замените на «-»"),
    "\u2014": ("длинное тире", "замените на «-»"),
    "\u2015": ("горизонтальная черта", "замените на «-»"),
    "\u2212": ("знак минус", "замените на «-»"),
    "\u00a0": ("неразрывный пробел", "замените обычным пробелом"),
}


def invalid_characters(text):
    """Текст -> [(номер строки с единицы, символ)], каждый символ строки — один раз."""
    found = []
    for number, line in enumerate((text or "").split("\n"), start=1):
        for char in dict.fromkeys(c for c in line if c in INVALID):
            found.append((number, char))
    return found


def described(found, where="строка", limit=5):
    """[(строка, символ)] -> «строка 2: длинное тире (U+2014) — замените на «-»; …»."""
    части = [f"{where} {number}: {INVALID[char][0]} (U+{ord(char):04X}) — {INVALID[char][1]}"
             for number, char in found[:limit]]
    if len(found) > limit:
        части.append(f"и ещё мест: {len(found) - limit}")
    return "; ".join(части)


#: Кавычки-ёлочки. bsl-ls их пропускает, а в коде кавычки прямые везде — и в
#: комментариях, и в текстах сообщений; проверка правок кода валит любую
#: добавленную строку с ними — в том числе в фрагменте, который выдал сам
#: инструмент.
GUILLEMETS = "«»"


def guillemet_lines(text):
    """Номера строк (с единицы), где есть кавычки-ёлочки."""
    return [number for number, line in enumerate((text or "").split("\n"), start=1)
            if any(c in line for c in GUILLEMETS)]


def line_numbers(found, limit=5):
    """[2, 5, 9] -> «строки 2, 5, 9»; длинный перечень — началом."""
    слово = "строка" if len(found) == 1 else "строки"
    хвост = f" и ещё {len(found) - limit}" if len(found) > limit else ""
    return f"{слово} {', '.join(map(str, found[:limit]))}{хвост}"
