def prefix_findings(new_objects, соглашения):
    """Новые объекты без приставки команды. `new_objects` — [(путь, вид, имя)]."""
    if not соглашения.приставка:
        return []
    return [FileFinding(ПРИСТАВКА, f"новый объект «{вид}.{имя}» без приставки «{соглашения.приставка}»",
                        путь)
            for путь, вид, имя in new_objects if not соглашения.своё(имя)]


# --- метки вставок ------------------------------------------------------------------

#: Разметка модуля, а не код: директивы областей вставками не оборачиваются.
#: Регистр не важен — так ищет и сам язык.
REGION_DIRECTIVE = re.compile(r"^\s*#(Область|КонецОбласти|Region|EndRegion)\b", re.IGNORECASE)
TYPE_WORD = re.compile(r"(ИЗМЕНЕН|ДОБАВЛЕН|УДАЛЕН)")
TYPE_WORD_YO = re.compile(r"(ИЗМЕНЁН|ДОБАВЛЁН|УДАЛЁН)")
DATE = re.compile(r"\d{2}\.\d{2}\.\d{4}")
#: ИД задачи — последний «#» строки; терпимость: «#» со цифрой где угодно —
#: так бывает, когда за ИД дописано пояснение.
TASK_AT_END = re.compile(r"#\S+\s*$")
TASK_WITH_DIGIT = re.compile(r"#[A-Za-zА-Яа-яЁё0-9_-]+\d")


def _значимая(line):
    return bool(line.strip()) and not REGION_DIRECTIVE.match(line)


def _номера(numbers, limit=5):
    shown = ", ".join(map(str, numbers[:limit]))
    return shown + ("…" if len(numbers) > limit else "")


def marker_findings(path, old, new, hunks, task=None):
    """Метки вставок в изменённом модуле: сама метка, правка вне вставок,
    правка внутри вставки другой задачи (`task` — ИД задачи; без него это
    правило не проверяется).

    Модуль, созданный задачей, сюда не попадает: внутри него меток нет вовсе.
    Пустые строки и директивы областей — вне правил: пустая строка снаружи
    вставки её отделяет, а директивы вставками не оборачиваются.
    """
    added, removed = changed_lines(hunks, old, new)
    added = [n for n in added if _значимая(new[n - 1])]
    removed = [n for n in removed if _значимая(old[n - 1])]
    found = []
    for n in added:
        line = new[n - 1]
        if marker_kind(line) != "open":
            continue
        метка = line.strip()
        if TYPE_WORD_YO.search(line):
            found.append(FileFinding(ВСТАВКА_Ё, "тип вставки написан через «Ё»; по словам ИЗМЕНЕН, "
                                                "ДОБАВЛЕН, УДАЛЕН вставки ищут по всей выгрузке", path, n))
        elif not TYPE_WORD.search(line):
            found.append(FileFinding(ВСТАВКА_БЕЗ_ТИПА, "в открывающей метке нет типа ИЗМЕНЕН/ДОБАВЛЕН/"
                                                       f"УДАЛЕН: {метка}", path, n))
        if not DATE.search(line):
            found.append(FileFinding(ВСТАВКА_БЕЗ_ДАТЫ, f"в открывающей метке нет даты дд.мм.гггг: {метка}",
                                     path, n))
        if not TASK_AT_END.search(line) and not TASK_WITH_DIGIT.search(line):
            found.append(FileFinding(ВСТАВКА_БЕЗ_ЗАДАЧИ, "в открывающей метке нет ИД задачи (#<ИД>): "
                                                         f"{метка}", path, n))

    new_ranges = marker_ranges(new)
    old_ranges = marker_ranges(old)
    комментарии = {строка.strip()[2:].strip() for строка in new if строка.strip().startswith("//")}

    def внутри(n, ranges):
        return any(r["start"] <= n <= r["end"] for r in ranges)

    вне = [n for n in added if not внутри(n, new_ranges)]
    стёрто = [n for n in removed if not внутри(n, old_ranges)
              and old[n - 1].strip() not in комментарии]
    if вне or стёрто:
        части = []
        if вне:
            части.append(f"добавленных вне вставок: {len(вне)} (стр. {_номера(вне)})")
        if стёрто:
            части.append(f"удалённых вне вставок: {len(стёрто)} (стр. {_номера(стёрто)} прежней версии)")
        found.append(FileFinding(ВНЕ_ВСТАВКИ, "; ".join(части), path))

    if task:
        чужие = []
        for n in added:
            вокруг = [r for r in new_ranges if r["start"] <= n <= r["end"]]
            if вокруг and not any(r["task"] == task for r in вокруг):
                чужие.append((n, max(вокруг, key=lambda r: r["start"])["task"]))
        if чужие:
            found.append(FileFinding(
                В_ЧУЖОЙ_ВСТАВКЕ, f"строк внутри вставки другой задачи ({чужие[0][1] or 'без ИД'}): "
                                 f"{len(чужие)} (стр. {_номера([n for n, _ in чужие])}) — нужна своя "
                                 "вставка поверх", path))
    return found


def structure_findings(path, new, added):
    """Вставки, поставленные задачей: открывающая метка без закрывающей и
    вставка вокруг метода, закрытая не на его конце. `added` — номера
    добавленных задачей строк новой версии."""
    added = set(added)
    found = []
    unclosed = set(unclosed_markers(new))
    for n in sorted(unclosed & added):
        found.append(FileFinding(НЕ_ЗАКРЫТА, "открывающая метка вставки без закрывающей: вставка не закрыта",
                                 path, n))
    объявления = [(n, m.group(1)) for n, m in ((n, DECLARATION.match(code_part(line)))
                                              for n, line in enumerate(new, start=1)) if m]
    for decl, name in объявления:
        end = _конец_метода(new, decl)
        if end is None:
            continue
        k = decl - 1
        while k >= 1 and _шапка(new[k - 1]):
            k -= 1
        if (k >= 1 and marker_kind(new[k - 1]) == "open" and k in added and k not in unclosed
                and marker_kind(new[end - 1]) != "close"):
            found.append(FileFinding(
                МЕТОД_НЕ_НА_КОНЦЕ, f"вставка вокруг метода {name} (метка на строке {k}): закрывающая "
                                   f"метка должна стоять на строке {new[end - 1].strip()}", path, end))
    return found


def _шапка(line):
    """Над объявлением метода — его часть: пустые строки, директивы, описание."""
    t = line.strip()
    return not t or t.startswith("&") or (t.startswith("//") and marker_kind(line) is None)


def _конец_метода(lines, decl):
    for n in range(decl + 1, len(lines) + 1):
        code = code_part(lines[n - 1]).strip()
        if METHOD_END.match(code):
            return n
        if DECLARATION.match(code):
            return None
    return None


# --- состав и формат файлов ------------------------------------------------------------


def service_findings(paths):
    """Служебные файлы выгрузки в правках. `paths` — пути, которые площадка
    назвала служебными: их пересобирает платформа, и в изменениях задачи их
    быть не должно."""
    return [FileFinding(СЛУЖЕБНЫЙ_ФАЙЛ, f"{путь.rsplit('/', 1)[-1]} в правках: его пересобирает "
                                        "платформа — верните файл к базе", путь)
            for путь in paths]


def eol_counts(data):
    """(CRLF, одиночных LF) в байтах файла."""
    crlf = data.count(b"\r\n")
    return crlf, data.count(b"\n") - crlf


def format_findings(path, data, accepted_eol=None):
    """BOM и переводы строк файла. `accepted_eol` — «CRLF» или «LF», принятые
    в репозитории; `None` — сверять не с чем (git нормализует их сам или
    репозитория нет)."""
    found = []
    if not data.startswith(b"\xef\xbb\xbf"):
        found.append(FileFinding(БЕЗ_BOM, "файл без BOM: конфигуратор может прочитать его не в UTF-8",
                                 path))
    crlf, lf = eol_counts(data)
    if crlf and lf:
        found.append(FileFinding(ПЕРЕВОДЫ_СМЕШАНЫ, f"смешанные переводы строк ({crlf} CRLF / {lf} LF)", path))
    elif accepted_eol is not None:
        своё = "CRLF" if crlf else "LF" if lf else None
        if своё is not None and своё != accepted_eol:
            found.append(FileFinding(ПЕРЕВОДЫ_ЧУЖИЕ, f"переводы строк {своё}, в репозитории приняты "
                                                     f"{accepted_eol}", path))
    return found


#: Строка с хвостовыми пробелами — пробел или табуляция перед переводом строки.
TRAILING = re.compile(rb"[ \t]+\r?\n")


def trailing_findings(path, old_data, new_data):
    """Хвостовых пробелов меньше, чем в эталоне, — срез при записи или законная
    замена строк; счётчик грубее сопоставления, поэтому предупреждение, а
    точный ответ даёт нормализация."""
    old, new = len(TRAILING.findall(old_data)), len(TRAILING.findall(new_data))
    if new >= old:
        return []
    return [FileFinding(ХВОСТЫ_СРЕЗАНЫ, f"строк с хвостовыми пробелами меньше, чем в эталоне ({old} -> {new}): "
                                        "срез при записи или замена строк — точный ответ даст нормализация",
                        path)]


def cosmetic_findings(path, old, new, hunks):
    """Строка, заменённая на себя же с другими пробелами. В изменениях она
    выглядит правкой, к задаче отношения не имеет и при обновлении вендора даёт
    ложный конфликт. Пустые строки не в счёт: пустая строка вставки на месте
    пустой строки с отступом — следствие оформления, а не правка."""
    removed, added = [], []
    for hunk in hunks:
        removed += [old[o - 1] for o in hunk.old_lines if o <= len(old)]
        added += [(n, new[n - 1]) for n in hunk.new_lines if n <= len(new)]
    по_сути = {}
    for n, text in added:
        по_сути.setdefault(re.sub(r"\s+", "", text), []).append((n, text))
    found = []
    for text in removed:
        суть = re.sub(r"\s+", "", text)
        if not суть:
            continue
        пара = next(((n, a) for n, a in по_сути.get(суть, ()) if a != text), None)
        if пара is not None:
            показ = суть if len(суть) <= 60 else суть[:60] + "…"
            found.append(FileFinding(ТОЛЬКО_ПРОБЕЛЫ, f"строка отличается от прежней только пробелами: «{показ}»",
                                     path, пара[0]))
    return found


