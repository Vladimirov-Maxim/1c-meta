"""Понятия, которыми домен разговаривает с остальными слоями.

Здесь нет ни XML, ни файлов, ни путей — нет даже имён тегов выгрузки: их знает
слой перекладки (`acl/mapping.py`). Домен называет вещи так, как
их называет разработчик в конфигураторе: «источник», «событие», «обработчик»,
«ПриЗаписи». Во что это превращается на диске, знает только перекладка.

Зачем так. Инварианты меняются чаще всего остального: у одних только подписок
четыре правила, которые нигде не записаны. Формат выгрузки
меняется реже всего — версия 2.21 живёт от релиза платформы до релиза. Пока
домен не знает про формат, правка инварианта не может задеть запись, а смена
версии формата — инварианты. Это выполняется по построению, а не по договорённости.
"""


class Refuse(Exception):
    """Отказ операции. Частичного применения не бывает — либо всё, либо ничего.

    Поднимается там, где продолжать значит угадывать: неизвестное событие,
    отсутствующий вид объекта, невыразимое в формате значение.
    """


class Finding:
    """Найденное нарушение инварианта: код правила, объяснение, поле.

    Код нужен, чтобы находка имела устойчивую идентичность и её можно было
    обрабатывать машинно, а не разбирать текст сообщения.

    `level` различает две вещи: `ERROR` — писать нельзя, `WARNING` —
    написать можно, но человек должен посмотреть. Смешивать их нельзя: если
    всё подряд ошибка, инструмент начнут обходить.
    """

    ERROR = "ошибка"
    WARNING = "предупреждение"

    def __init__(self, code, message, field=None, level=ERROR):
        self.code = code
        self.message = message
        self.field = field
        self.level = level

    @property
    def blocking(self):
        return self.level == Finding.ERROR

    def __str__(self):
        where = f" ({self.field})" if self.field else ""
        return f"[{self.code}]{where} {self.message}"


class Host:
    """Окружение вложенной сущности: чей это ребёнок и заведён ли хозяин.

    Три разных правила спрашивают три разные вещи, и слипаться им нельзя:
    состав свойств зависит от **вида** хозяина, префикс — от его **имени**,
    а проверки «объект есть» и «имя занято» — от того, **существует** ли он
    уже в выгрузке.

    Одной парой «(вид, имя)» это не выразить: у ребёнка, создаваемого вместе
    с объектом, имя пришлось бы обнулять — иначе проверка искала бы на диске
    карточку, которой ещё нет. Обнулённое имя заодно отключало бы и правило
    префикса: оно держалось бы не на факте, а на рассуждении «объект
    создаётся, значит он наш, значит ребёнку префикс не нужен». Рассуждение
    верное, но нигде не записанное — и молча сломалось бы, появись для имени
    объекта исключение.

    `of` принимает и пару, и готового хозяина: пара означает существующий
    объект — так её и передают все вызывающие.

    Имя объекта, от которого зависит префикс, не хранится вторым полем,
    а выводится из адреса (`owner_name`). Второе поле повторяло бы адрес,
    а инвариант «говорят одно» нигде не записан — и хватило бы одного места
    сборки, где правка свойства передаёт имя ближайшего родителя, а не
    объекта, чтобы они разошлись.
    """

    def __init__(self, kind=None, name=None, exists=True, path=()):
        self.kind = kind
        self.name = name
        self.exists = exists
        # Полный адрес хозяина парами «вид, имя». Нужен четвёртому вопросу,
        # который первыми тремя не подменить: «какие имена внутри уже
        # заняты». У реквизита табличной части это имена внутри неё, а не
        # внутри объекта, и одной парой такой вопрос не задать.
        self.path = tuple(path)

    @property
    def owner_name(self):
        """Имя объекта верхнего уровня — то, от которого зависит префикс.

        Реквизит внутри «мой_Проба.Строки» живёт в нашем объекте, хотя сама
        табличная часть зовётся «Строки». Когда адреса нет (объект только
        создаётся), остаётся `name`: там он и есть имя объекта.
        """
        return self.path[0][1] if self.path else self.name

    @classmethod
    def of(cls, context):
        if context is None:
            return cls()
        if isinstance(context, cls):
            return context
        kind, name = context
        return cls(kind, name, path=((kind, name),))

    def __repr__(self):
        return f"Host({self.kind!r}, {self.name!r}, exists={self.exists}, path={self.path!r})"


def представление(spec):
    """Чем называть сущность в отчёте и в плане.

    У пункта настроек компоновки имени нет вовсе, и без этого вместо
    представления в план попало бы питоновское `None`: «добавить «None» в …».
    Просмотр перед
    записью ради того и нужен, чтобы увидеть, что добавляется, — а по такому
    плану проверить нечего, кроме числа строк. Называем тем, чем сущность
    опознаётся: полем, левым операндом, путём к данным.
    """
    for поле in ("имя", "поле", "левое", "путьКДанным"):
        значение = spec.get(поле)
        if значение:
            return str(значение)
    return "без имени"


class ValueType:
    """Тип значения. Общий предок — чтобы «тип» можно было отличить от чего угодно.

    Замысел один: квалификатор не бывает отдельно от типа. В замеренной
    выгрузке это правило соблюдается без исключений — все 6697 строковых
    реквизитов несут
    `StringQualifiers`, все 2907 числовых — `NumberQualifiers`, все 2801
    датовых — `DateQualifiers`. Поэтому «строку без длины» здесь нельзя
    выразить: не «не рекомендуется», а не собирается.

    Тип печатается краткой записью задания — той, что принимают и задание на
    формы, и задание на метаданные: что выдал просмотр, то и вставляется в
    задание. Печать в своём формате — `Число(10.0)`, `Дата(ДатаВремя)`,
    `Справочник.X (Ссылка)` — задание бы не приняло.
    """

    def __repr__(self):
        # Список печатает элементы через `repr`: без этого составной тип
        # выглядел бы в просмотре адресами в памяти.
        return str(self)


def запись_типа(vtype):
    """Тип или составной тип (список) -> краткая запись задания.

    Части составного — через «|», как их и пишут в задании: запятая уже
    занята внутри скобок («Число(15,2)»).
    """
    if isinstance(vtype, (list, tuple)):
        return " | ".join(запись_типа(x) for x in vtype)
    return str(vtype)


class StringType(ValueType):
    def __init__(self, length, fixed=False):
        self.length = length
        self.fixed = fixed

    def __str__(self):
        return "Строка({}{})".format(self.length, ", фиксированная" if self.fixed else "")


class NumberType(ValueType):
    def __init__(self, digits, fraction_digits=0, nonnegative=False):
        self.digits = digits
        self.fraction_digits = fraction_digits
        self.nonnegative = nonnegative

    def __str__(self):
        return "Число({},{}{})".format(self.digits, self.fraction_digits,
                                       ", неотрицательное" if self.nonnegative else "")


