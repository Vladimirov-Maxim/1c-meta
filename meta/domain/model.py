class TypeRef(ValueType):
    """Ссылка на тип в доменных словах: вид метаданных, имя, грань.

    `name=None` — имени нет: ссылка не на конкретный объект.

    Грань — с какой стороны объект участвует: «Объект», «Менеджер»,
    «НаборЗаписей», «МенеджерЗначения». Ровно эти четыре встречаются
    в 639 подписках замеренной конфигурации. `facet=None` — грани нет вовсе; так устроен
    определяемый тип: он сам раскрывается в набор типов, и какая у них грань,
    видно только по его карточке (95 источников из 639 — не редкий случай).

    `is_set` — набор типов или один тип. Признак самостоятельный, вывести его
    не из чего: встречаются оба безымянных случая сразу — «все объекты
    документов» (набор) и тип «ДокументМенеджер» (один абстрактный тип). Имени
    нет у обоих, а смысл разный, и записаны они разными тегами. Поэтому признак
    задают явно, для чего есть `набор` и `определяемый`.
    """

    #: Виды без грани -> набор ли это. Наборы: определяемый тип,
    #: характеристика плана видов характеристик (имя — сам план), «любая
    #: ссылка» (имени нет). Одиночные: точка маршрута бизнес-процесса (бывает
    #: и с именем, и без), построитель отчёта, набор констант.
    FACETLESS = {"ОпределяемыйТип": True, "Характеристика": True, "ЛюбаяСсылка": True,
                 "ТочкаМаршрутаБизнесПроцесса": False, "ПостроительОтчета": False,
                 "НаборКонстант": False}

    #: Из них пишутся без имени.
    NAMELESS = ("ЛюбаяСсылка", "ТочкаМаршрутаБизнесПроцесса", "ПостроительОтчета",
                "НаборКонстант")

    def __init__(self, kind, name=None, facet="Объект", is_set=False):
        self.kind = kind
        self.name = name
        self.facet = facet
        self.is_set = is_set

    @classmethod
    def of_kind(cls, kind, facet="Объект"):
        """Весь вид целиком: «все объекты документов».

        Имя не `is_set`: так зовётся признак экземпляра, и одноимённый
        конструктор работал бы только по случайности — атрибут экземпляра
        перекрывает метод класса. Читалось бы как ошибка и сломалось бы
        от любой перестановки. И не `whole_kind`: этим именем уже назван
        вопрос «весь ли это вид», а конструктор отвечает на другой.
        """
        return cls(kind, None, facet, is_set=True)

    @classmethod
    def defined(cls, name):
        """Определяемый тип: набор по определению, грани не имеет."""
        return cls("ОпределяемыйТип", name, None, is_set=True)

    @property
    def whole_kind(self):
        return self.name is None

    def __str__(self):
        if self.name is None and self.facet is None:
            return self.kind                       # «ЛюбаяСсылка»
        # Грань «Ссылка» подразумевается: так ссылку пишет задание
        # («Справочник.Контрагенты»), прочие грани названы.
        facet = f" ({self.facet})" if self.facet and self.facet != "Ссылка" else ""
        return "{}.{}{}".format(self.kind, self.name or "*", facet)


#: Табличная часть объекта, который в базе не хранится, — обработки или
#: отчёта. Отдельным «видом хозяина» она названа потому, что состав свойств
#: её реквизитов другой: заполнение есть, а индексирования, полнотекстового
#: поиска и истории данных нет. Замерено: 6794 реквизита у хранимых против
#: 4411 у нехранимых, без единого исключения.
#:
#: Синтетический вид — не выдумка про предметную область, а имя различию,
#: которое в ней есть: сказать «реквизит табличной части» недостаточно,
#: нужно знать, чьей.
НЕХРАНИМАЯ_ТЧ = "ТабличнаяЧастьНехранимого"

#: Виды, чьи табличные части хранятся в базе.
ХРАНИМЫЕ = ("Справочник", "Документ", "ПланОбмена", "БизнесПроцесс",
            "ПланВидовХарактеристик", "Задача")


def вид_табличной_части(владелец):
    """Вид хозяина для реквизитов табличной части такого владельца."""
    return "ТабличнаяЧасть" if владелец in ХРАНИМЫЕ else НЕХРАНИМАЯ_ТЧ


class Собранные:
    """Отказы копятся и предъявляются разом.

    Домен собирает все свои находки и печатает их вместе; отказы же — из
    диалекта, из перекладки, из поиска адресов — без этого рвали бы работу
    на первом же. Внутри одного запуска выходило бы два разных характера
    поведения, и предсказать, какой достанется, было бы нельзя: два
    поля-длины числом — два запуска, четыре беды в описании типа — четыре.

    Записи не происходит ни в том, ни в другом случае: страдает не
    корректность, а цикл работы.

    Живёт в домене, потому что нужен трём слоям сразу, а домен — общий
    для всех и не тянет за собой ничего.
    """

    def __init__(self, заголовок="не вышло"):
        self.заголовок = заголовок
        self.беды = []

    def добавить(self, что):
        self.беды.append(что)

    def __bool__(self):
        return bool(self.беды)

    def предъявить(self):
        if not self.беды:
            return
        if len(self.беды) == 1:
            raise Refuse(self.беды[0])
        raise Refuse(f"{self.заголовок} ({len(self.беды)}):\n   "
                     + "\n   ".join(self.беды))


class ListEdit:
    """Правка поля-перечня («состав» подсистемы, «движения» документа):
    добавить, убрать — или заменить целиком, но только когда это сказано.

    Перечень в правке голым списком означал бы замену, а замену здесь
    почти никогда не хотят: в составе подсистемы десятки чужих объектов,
    и список из одного добавляемого молча выкинул бы остальные.
    """

    def __init__(self, add=(), remove=(), replace=None):
        self.add = tuple(add)
        self.remove = tuple(remove)
        self.replace = None if replace is None else tuple(replace)

    def applied(self, current):
        """(новый перечень, уже было, не было) против записанного `current`.

        Порядок записанного сохраняется, добавленное — в конец, повтор
        добавляемого не дублируется."""
        if self.replace is not None:
            return list(self.replace), [], []
        было = list(current)
        уже = [x for x in self.add if x in было]
        нет = [x for x in self.remove if x not in было]
        новый = [x for x in было if x not in self.remove]
        for x in self.add:
            if x not in новый:
                новый.append(x)
        return новый, уже, нет

    def added(self, current):
        """Что появится в перечне сверх записанного."""
        return [x for x in (self.replace if self.replace is not None else self.add)
                if x not in current]

    def __repr__(self):
        части = [f"{слово} {list(что)}" for слово, что in
                 (("добавить", self.add), ("убрать", self.remove)) if что]
        if self.replace is not None:
            части = [f"заменить {list(self.replace)}"]
        return "; ".join(части)


class Spec:
    """Что просят создать, на языке домена: вид объекта и поля.

    Поля — обычный словарь с русскими ключами. Это данные, а не код: их состав
    объявляет вид (`Kind.fields`), их смысл знают инварианты, их укладку — перекладка.
    """

    def __init__(self, kind, fields, asked=None, existing=False):
        self.kind = kind
        self.fields = dict(fields)
        #: Поля, которые назвал человек, — в отличие от подставленных
        #: умолчаний. Без них просмотр, печатающий только отличное от
        #: умолчания, молчал бы ровно о том, что человек написал руками:
        #: заданный «видИерархии: ГруппыИЭлементы» совпадает с умолчанием и
        #: исчез бы, и отличить «принято» от «не разобрано» было бы нельзя.
        self.asked = frozenset(fields if asked is None else asked)
        #: Объект уже есть в выгрузке, а задание к нему лишь обращается:
        #: удалить, переименовать, поправить поля. Умолчаний у него нет —
        #: неназванные поля остаются такими, какие записаны. Без признака
        #: просмотр печатал бы под удалением «ещё 51 поле не названо —
        #: значения по умолчанию».
        self.existing = existing

    def get(self, name, default=None):
        return self.fields.get(name, default)

    def __getitem__(self, name):
        return self.fields.get(name)

    def __contains__(self, name):
        return name in self.fields


class Configuration:
    """Порт: что домену нужно знать о конфигурации, чтобы проверять инварианты.

    Реализует инфраструктура — чтением выгрузки. Домен не знает, откуда берутся
    ответы: из файлов, из индекса или из заглушки в тесте. Благодаря этому
    инварианты проверяются юнит-тестом за миллисекунды, без временного репозитория.

    Ответ `None` означает «не смог определить» и отличается от `False`
    («точно нет»). Инвариант, получивший `None`, обязан выдать предупреждение,
    а не ошибку: молча пропустить нельзя, но и обвинять не в чем.
    """

    def common_module_exists(self, name):
        raise NotImplementedError

    def common_module_flags(self, name):
        """Признаки контекста общего модуля: {«сервер»: True, «вызовСервера»:
        False, …} — или None: модуля нет или прочитать не удалось."""
        return None

    def common_module_lines(self, name):
        """Строки модуля общего модуля или `None` — модуля нет."""
        return None

    def form_module_lines(self, owner, name):
        """Строки модуля формы или `None` — модуля нет. `owner` — пара (вид,
        имя) хозяина, `None` — общая форма. Нужны, чтобы назвать номером
        строки, куда ляжет вызов кода доработки формы, и увидеть элементы,
        которые модуль формы уже добавляет кодом."""
