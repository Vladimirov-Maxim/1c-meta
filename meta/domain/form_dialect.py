"""Язык кода доработки формы: что в коде зависит от языка, а не от описания формы.

Типовую форму правят только кодом, и описание правки одно — меняются слова,
которыми оно записано. Встроенный язык — «платформа»: методы, которые есть
в любой конфигурации (`Новый РеквизитФормы`, `Элементы.Вставить`,
`УстановитьДействие`). Свой язык — например, построитель форм команды —
подключается файлом-диалектом из профиля (`кодФормы.диалект`): это модуль
Python с объектом `DIALECT`, наследником `FormCodeDialect`, у которого
переопределено то, что у его языка иначе.

Домен знает только этот договор. Код платформы пишет перекладка
(`acl.platform_code`), код диалекта — сам диалект.
"""

from typing import NamedTuple

from .model import Refuse


class CodeProcedure(NamedTuple):
    """Процедура доработки формы в модуле: границы и строка, перед которой
    дописывается новый код. `variable` — имя, которое язык держит в процедуре
    (например, переменная построителя); у кода платформы его нет."""

    start: int
    end: int
    variable: str | None
    insert_line: int


class FormCodeDialect:
    """Договор языка кода формы. Поведение по умолчанию — язык платформы.

    `настройки` у каждого метода — всё из раздела «кодФормы» профиля, кроме
    «язык» и «диалект»: модуль, функция создания и прочее, что нужно языку.
    """

    #: имя языка, как его пишет профиль («кодФормы.язык»)
    name = "платформа"
    #: как ответ называет выданный фрагмент
    title = "Код доработки формы"
    #: Как код этого языка заводит элемент, реквизит и команду формы — шаблон
    #: начала вызова до скобки с именем. По нему узнаётся, что имя уже
    #: заводится кодом модуля: второй элемент с тем же именем форма не примет.
    #: Вызовы платформы проверяются всегда — модуль формы пишет и вендор.
    creating = {
        "элемент": r"Элементы\s*\.\s*(?:Добавить|Вставить)",
        "реквизит": r"Новый\s+РеквизитФормы",
        "команда": r"Команды\s*\.\s*Добавить",
    }

    def check(self, settings):
        """Настройки из профиля; неверные — отказ с объяснением, а не догадка."""
        if settings:
            raise Refuse("у языка платформы настроек нет, а указаны: "
                         + ", ".join(sorted(settings)))

    def description(self, settings):
        """Каким кодом выдаётся фрагмент — словами для инструкции сервера."""
        return "методами платформы"

    def purpose(self, settings):
        """Хвост описания процедуры доработки: «Дорабатывает форму X<хвост>.»."""
        return ""

    def code(self, edits, view, settings):
        """Правки формы -> текст фрагмента для `ПриСозданииНаСервере`.

        У платформы его пишет перекладка; диалект обязан переопределить.
        """
        raise NotImplementedError

    def procedure_sign(self, settings):
        """По чему узнаётся процедура доработки — словами, для отказа."""
        return "у процедуры доработки формы один параметр — форма"

    def procedure(self, lines, span, arity, settings):
        """Процедура доработки в границах `span` -> `CodeProcedure` или `None`,
        если дополнять её нечем узнать. `arity` — сколько параметров у метода,
        если известно. Код платформы дописывается перед «КонецПроцедуры»."""
        if arity not in (None, 1):
            return None
        return CodeProcedure(span[0], span[1], None, span[1])

    def extension_anchor(self, procedure):
        """Строка, перед которой дописывается код, — словами: «её «КонецПроцедуры»»."""
        return "её «КонецПроцедуры»"

    def extension_place(self, procedure):
        """Куда в существующей процедуре ложится новый код — словами для ответа."""
        return f"код перед {self.extension_anchor(procedure)}"

    def extension(self, lines, procedure, settings):
        """Строки нового фрагмента -> строки, которые дописываются в процедуру.
        Код платформы дописывается как есть: его переменные переприсваиваются."""
        lines = list(lines)
        while lines and not lines[0].strip():
            lines.pop(0)
        return lines

    def movement(self, next_):
        """Как в коде записано «встать перед `следующий`» — для пояснений."""
        return f"Элементы.Вставить(…, Элементы.{next_})"

    def findings(self, edits, settings):
        """Чего язык не выражает из описания формы — находки до выдачи кода."""
        return []


#: Встроенный язык — один на всех.
PLATFORM = FormCodeDialect()
