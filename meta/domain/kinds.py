# Имя объекта метаданных в 1С: буквы (в т. ч. русские), цифры, подчёркивание;
# цифра первой не допускается.
NAME_RE = re.compile(r"^[A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё_0-9]*$")


#: Как назвать знак, которого в имени быть не должно. Печатать сам знак мало:
#: пробел и неразрывный пробел на экране не отличить.
ЗНАКИ = {" ": "пробел", "-": "дефис", ".": "точка", ",": "запятая",
         "/": "косая черта", "\\": "обратная косая", "(": "скобка",
         ")": "скобка", '"': "кавычка", "'": "апостроф", "+": "плюс",
         "%": "процент", "#": "решётка", "&": "амперсанд", ":": "двоеточие",
         ";": "точка с запятой", "!": "восклицательный знак",
         "?": "вопросительный знак", "*": "звёздочка", "=": "равно",
         "\t": "табуляция", "\n": "перевод строки"}


def почему_имя_плохое(name):
    """Что именно не так с именем: одно «не является именем» не объясняет ничего.

    Имя объекта метаданных — буквы, цифры и подчёркивание, первым знаком
    не цифра. У «мой_Лимиты Тест-2024» дефектов сразу два, и без перечня
    пришлось бы гадать, какой из них имели в виду.
    """
    if not name:
        return "имя пустое"
    причины = []
    if name[0].isdigit():
        причины.append("начинается с цифры")
    плохие = [c for c in dict.fromkeys(name) if not NAME_RE.match("x" + c)]
    if плохие:
        причины.append("недопустимые знаки: " + ", ".join(
            ЗНАКИ.get(c, f"«{c}»") for c in плохие))
    return "; ".join(причины) or "знаки допустимы только буквенно-цифровые"


def про_неизвестные_поля(unknown, known, вид):
    """Текст про незнакомые поля: сначала подсказка, потом куда смотреть.

    Иначе на две опечатки вываливались бы все 55 имён полей одной строкой, и
    нужное слово в ней пришлось бы искать глазами. Опечатка же почти всегда в
    одну букву.
    """
    куски = []
    for поле in sorted(unknown):
        # Порог замерен на настоящих опечатках в заданиях — и в том самом
        # порядке сравнения, который применяет `get_close_matches` (он не
        # симметричен: в обратном порядке оценка выше на 0.09):
        # «коментарий»/«комментарий» 0.95, «синонимм»/«синоним» 0.93,
        # «типНомеров»/«типНомера» 0.84, «иерархичный»/«иерархический» 0.75,
        # «индексация»/«индексирование» 0.58. Не-опечатки не поднимаются
        # выше 0.31 («состав» против «синоним»), так что 0.55 их отсекает.
        близкие = difflib.get_close_matches(поле, known, n=2, cutoff=0.55)
        куски.append(f"«{поле}»" + (f" — возможно, {' или '.join(близкие)}"
                                    if близкие else ""))
    # Порог — не круглое число, а граница между «прочитал строку» и «ищу
    # глазами»: у перечисления полей 16 и список полезен, у справочника 55
    # и он превращается в экран текста.
    # Как спросить перечень, знает канал, а не домен: совет «--поля» был бы
    # на языке терминала, а через MCP он ничего не говорит.
    хвост = (", ".join(known) if len(known) <= 20
             else f"их {len(known)}, перечень — в справке по полям вида «{вид}»")
    return "вид «{}» не знает полей: {}; известны: {}".format(
        вид, "; ".join(куски), хвост)


class Kind:
    """Вид объекта метаданных."""

    name = None        # доменное имя вида, например "ПодпискаНаСобытие"
    fields = ()        # словарь полей вида, на языке домена
    required = ()      # без чего объект не имеет смысла
    defaults = {}      # чем заполняются незаданные поля
    child_fields = ()  # (доменное поле, вид ребёнка) — вложенные сущности
    #: Соглашения команды — приставка и уровни правил из её профиля. У вида из
    #: общего реестра — нейтральные; `kind_of(имя, соглашения)` даёт копию вида
    #: с соглашениями команды.
    соглашения = НЕЙТРАЛЬНЫЕ
    APPLIES_TO = {}    # свойство -> виды хозяев, у которых оно бывает

    @property
    def prefix(self):
        """Приставка доработок команды; `None` — соглашения о ней нет."""
        return self.соглашения.приставка

    def fill(self, spec, context=None):
        """Спецификация с подставленными умолчаниями.

        Умолчания — решение предметной области («каким заводится новый модуль»),
        а не формата, поэтому живут здесь. Исходная спецификация не меняется:
        вызывающий должен видеть, что именно он задал.

        `context` — окружение, то же, что у `check`: часть умолчаний зависит
        от объекта-хозяина. Без него инструмент подставил бы реквизиту
        табличной части значение заполнения, которого у неё нет, и сам же на
        него ругался бы.
        """
        fields = dict(self.defaults)
        fields.update(spec.fields)
        # Детям умолчания нужны так же, как объекту: без них платформа отвергает
        # карточку — «Ошибка XDTO… Тип: FillChecking», пустое значение
        # перечисления недопустимо.
        for field, child_kind in self.child_fields:
            child_of = REGISTRY.get(child_kind)
            if child_of is not None:
                fields[field] = [child_of.fill(child, self._child_host(spec, context))
                                 for child in fields.get(field) or []]
        return spec.__class__(spec.kind, fields, asked=spec.asked)

    def _child_host(self, spec, context=None):
        """Хозяин для детей: вид — свой, имя — объекта верхнего уровня.

        Вид нужен составу свойств: у реквизита табличной части он свой.
        Имя нужно правилу префикса, а оно про объект, а не про ближайшего
        родителя: реквизит внутри «мой_Проба.Строки» живёт в нашем объекте,
        хотя сама табличная часть зовётся «Строки» и префикса не несёт.
        Поэтому имя объекта передаётся вглубь неизменным.
        """
        owner = Host.of(context)
        # У табличной части вид хозяина для её реквизитов зависит от того,
        # хранится ли объект: у обработки и отчёта состав другой (см.
        # `WITH_FILL`).
        вид = (вид_табличной_части(owner.kind) if self.name == "ТабличнаяЧасть"
               else self.name)
        return Host(вид, owner.name or spec.get("имя"),
                    exists=owner.exists if context is not None else False,
                    path=owner.path)

    def check_delete(self, path, config):
        """Инварианты удаления: не удалять то, на что ссылаются.

        Спрашивается через порт: сам поиск по выгрузке — дело инфраструктуры.
        Предупреждение о непроверенном идёт всегда и намеренно: инструмент
        смотрит карточки объектов и права ролей, но не формы и не код BSL.
        Молчание о непроверенном хуже, чем отказ проверять.
        """
        found = []
        who = None if config is None else config.references_to(path)
        if who is None:
            found.append(Finding(
                "УДАЛЕНИЕ-НЕПРОВЕРЕНО",
                "не удалось узнать, кто ссылается на объект — удаление вслепую",
                level=Finding.WARNING))
        elif who:
            shown = ", ".join(who[:8]) + ("…" if len(who) > 8 else "")
            found.append(Finding(
                "УДАЛЕНИЕ-ЕСТЬ-ССЫЛКИ",
                f"на «{_address(path)}» ссылаются ({len(who)}): {shown}"))
        elif self.inside_schema:
            # Снаружи такой адрес не назвать, и обратный поиск про него молчит
            # по существу, а не по бессилию. Но внутри схемы связи есть, и они
            # по именам полей: выбираемое поле называет поле набора данных,
            # отбор — тоже, запрос набора называет параметр. Обозначения там
            # нет, значит и проверить нечем — об этом и сказано.
            found.append(Finding(
                "УДАЛЕНИЕ-СХЕМА-СВЯЗИ-НЕ-ПРОВЕРЕНЫ",
                "снаружи на это сослаться нельзя, а связи внутри самой схемы "
                "идут по именам полей — выбираемые поля, отборы, порядок "
                "и запросы наборов инструмент не сверяет; проверьте отчёт "
                "в режиме предприятия",
                level=Finding.WARNING))
        else:
            found.append(Finding(
                "УДАЛЕНИЕ-КОД-НЕ-ПРОВЕРЕН",
                "в карточках объектов, реестре конфигурации, правах ролей "
                "и типах схем компоновки ссылок нет; формы, код BSL, тексты "
                "запросов и прочие макеты инструмент не смотрит — проверьте "
                "синтаксическим контролем",
                level=Finding.WARNING))
        return found

    def check_rename(self, new_name, config=None, context=None):
        """Инварианты переименования: имя допустимо, свободно и с префиксом.

        Ссылки здесь не помеха, а работа: переименование их переписывает.
        Помеха только одна — занятое имя.
        """
        found = []
        if not NAME_RE.match(new_name or ""):
            found.append(Finding(
                "МД-ИМЯ-НЕДОПУСТИМО",
                f"«{new_name}» не является именем объекта метаданных: "
                + почему_имя_плохое(new_name), "имя"))
            return found
        if self.needs_prefix(context) and not self.соглашения.своё(new_name):
            found.append(Finding(
                "МД-ПРЕФИКС",
                f"имя «{new_name}» без префикса «{self.prefix}»",
                "имя"))
        if config is not None and config.object_exists(self.name, new_name):
            found.append(Finding(
                "МД-ИМЯ-ЗАНЯТО",
                f"«{self.name}.{new_name}» в конфигурации уже есть", "имя"))
        return found

    def check_change(self, fields, context=None):
        """Проверка частичной правки: что можно проверить по самой правке.

        Полную проверку по неполной спецификации делать нельзя — правила вида
        смотрят на объект целиком, а здесь задан только сдвиг. Поэтому
        проверяется ровно то, что от сдвига зависит: известно ли поле, бывает
        ли оно у этого хозяина и не переименование ли это.
        """
        found = []
        unknown = [f for f in fields if f not in self.fields]
        if unknown:
            found.append(Finding(
                "МД-ПОЛЕ-НЕИЗВЕСТНО",
                про_неизвестные_поля(unknown, self.fields, self.name)))
        if "имя" in fields:
            found.append(Finding(
                "МД-ПЕРЕИМЕНОВАНИЕ",
                "имя объекта живёт не только в его карточке — ещё в реестре "
                "конфигурации, в порождаемых типах и в чужих карточках, которые "
                "на него ссылаются. Это отдельная операция, а не правка поля",
                "имя"))
        host_kind = Host.of(context).kind
        if host_kind:
            for field, kinds in self.APPLIES_TO.items():
                if field in fields and host_kind not in kinds:
                    found.append(Finding(
                        "РЕКВИЗИТ-ПОЛЕ-НЕ-ДЛЯ-ВИДА",
                        "у вида «{}» свойства «{}» нет; оно бывает у: {}".format(
                            host_kind, field, ", ".join(kinds)), field))
        return found

    #: Поля, которые правило связывает между собой: по одному их не проверить.
    RELATED = ()

    def related_findings(self, spec, config, changed):
        """Правка поля из связанной группы — проверка группы на объекте целиком.

        Правка проверяется сама по себе: собрать полную спецификацию из
        карточки без потерь нельзя. Но правило об отношении полей по одному
        полю не проверить: источник подписки, переставленный с документа на
        справочник при обработчике с четырьмя параметрами, прошёл бы без слова.
        Поэтому `spec` здесь —
        объект, как он лежит в выгрузке, с наложенной правкой, а находки —
        только о полях затронутых групп: об остальном объекте правка не
        спрашивала.
        """
        группы = [группа for группа in self.RELATED if set(группа) & set(changed)]
        if not группы:
            return []
        поля = set().union(*группы)
        return [f for f in self.own_findings(spec, config) if f.field in поля]

    def own_findings(self, spec, config, context=None):
        """Инварианты этого вида.

        База не знает ни одного — и это не заглушка, а честный ответ:
        у большинства плоских видов своих правил нет.
        """
        return []

    #: Поля-длины и их потолок. `None` — потолок неизвестен: длина наименования
    #: 200 проходит загрузку и остаётся 200, поэтому предел по корпусному
    #: максимуму 150 не выдумывается. У длины кода потолок
    #: доказан отказом платформы, дословно: «Длина кода превышает
    #: максимально допустимое значение - 50».
    LENGTH_FIELDS = {"длинаКода": MAX_CODE_LENGTH,
                     "длинаНаименования": None,
                     "длинаНомера": None}

    def length_findings(self, spec):
        """Длины записываются текстом, и без этой проверки их не проверял бы никто.

        `длинаКода: "9999"` ушла бы в файл с вердиктом «замечаний нет»,
        а платформа отвергает на ней всю загрузку. `длинаНаименования: "-10"`
        прошла бы туда же.
        """
        found = []
        for field, ceiling in self.LENGTH_FIELDS.items():
            if field not in self.fields:
                continue
            said = spec.get(field)
            if said in (None, ""):
                continue
            try:
                value = int(str(said))
            except ValueError:
                continue              # не число — про это скажет перекладка
            if value < 0:
                found.append(Finding(
                    "ДЛИНА-ОТРИЦАТЕЛЬНА",
                    f"{field} = {value}: длина не бывает отрицательной", field))
            elif ceiling is not None and value > ceiling:
                found.append(Finding(
                    "ДЛИНА-БОЛЬШЕ-ПРЕДЕЛА",
                    f"{field} = {value}, а платформа отвергает загрузку "
                    f"словами «Длина кода превышает максимально допустимое "
                    f"значение - {ceiling}»", field))
        return found

    def check(self, spec, config, context=None):
        """Общие инварианты + свои. Переопределять не нужно — есть `own_findings`.

        `контекст` — окружение, без которого часть правил не проверить: у реквизита
        это объект-хозяин. У самостоятельных объектов он пуст.
        """
        findings = self._common(spec, context)
        findings.extend(self.length_findings(spec))
        findings.extend(self.own_findings(spec, config, context) or [])
        findings.extend(self._children(spec, config, context))
        return findings

    def _children(self, spec, config, context=None):
        """Проверка вложенных сущностей, заданных вместе с объектом.

        Хозяина на диске ещё нет — об этом сказано признаком `exists`, а не
        обнулённым именем: проверки «объект есть» и «имя занято» отключаются
        им, а правило префикса продолжает опираться на настоящее имя.
        Занятость имени проверяется здесь же, среди своих.
        """
        found = []
        # Одно множество на объект, а не на поле: у платформы имена детей —
        # одно пространство, и реквизит «Строки» рядом с табличной частью
        # «Строки» она не примет: считай по полю, такой объект писался бы
        # без замечаний. Столкновений между видами детей в замеренной
        # конфигурации нет ни одного на 7035 объектов — это и есть основание.
        seen = set()
        # Своё имя без префикса делает объект «типовым» в глазах правила,
        # и тогда префикса требуют и от детей. Правило верное, но вторая
        # ошибка — следствие первой: исправив обе, человек получит
        # `мой_Лимиты` с реквизитом `мой_Сумма`, чего никто не просил.
        сам_без_префикса = any(f.code == "МД-ПРЕФИКС"
                               for f in self._common(spec, context))
        for field, child_kind in self.child_fields:
            children = spec.get(field) or []
            for место, child in enumerate(children, 1):
                # Умолчания детям подставил `fill` — здесь только проверка.
                name = child.get("имя")
                host = self._child_host(spec, context)
                for finding in kind_of(child_kind, self.соглашения).check(child, config, host):
                    if сам_без_префикса and finding.code == "МД-ПРЕФИКС":
                        continue          # следствие ошибки в имени объекта
                    # Без пути до ребёнка находку не к кому отнести: у объекта
                    # их бывает десяток, а печатается всё под именем объекта.
                    # Безымянного зовём по месту в списке: «значения[?]»
                    # не говорит, какое из четырёх значений виновато.
                    where = f"{field}[{name or место}]"
                    if finding.field:
                        where += "." + finding.field
                    found.append(Finding(finding.code, finding.message,
                                         where, finding.level))
                if name in seen:
                    found.append(Finding(
                        "ДЕТИ-ИМЯ-ПОВТОРЯЕТСЯ",
                        f"«{name}» задано дважды: у объекта имена реквизитов, "
                        "измерений, ресурсов и табличных частей — одно "
                        "пространство", field))
                seen.add(name)
        return found

    #: Поля, которые инструмент выводит сам, а не берёт из задания: ввод
    #: по строке собирается от имени объекта, значение заполнения — от типа.
    #: В просмотре им не место: он отвечает на вопрос «то ли я задал», а эти
    #: поля задавал не человек.
    derived = ("вводПоСтроке", "значениеЗаполнения")

    #: Самое длинное имя объекта в замеренной конфигурации — 80 символов на 22 292.
    #: Ограничения платформы по файлам выгрузки не видно, поэтому здесь
    #: не запрет, а предупреждение: за этой границей начинается незамеренное,
    #: а на Windows ещё и предел длины пути у файлов-спутников.
    LONGEST_MEASURED_NAME = 80

    #: Поля, значение которых — тип, а не текст, и как их читать:
    #: «значение» — грань «Ссылка» подразумевается (тип реквизита, тип
    #: параметра), «объект» — участвует объект целиком (источник подписки).
    #:
    #: Объявляет домен, потому что разбирает их диалект, а диалогу с acl
    #: он не обучен: перечислять такие поля в диалекте руками значило бы
    #: забыть очередное — и тип, ушедший в перекладку словарём из JSON,
    #: ронял бы её изнутри с `AttributeError: 'dict' has no 'is_set'`.
    type_fields = {}

    #: Живёт внутри схемы компоновки, а не в карточке объекта. Это факт
    #: предметной области того же рода, что `HOSTS` у вложенных видов:
    #: у набора данных, параметра и пункта настроек хозяин — схема.
    #: Инвариант удаления от него зависит: снаружи такой адрес не назвать
    #: обозначением, зато внутри схемы на него ссылаются по имени поля,
    #: и этих связей инструмент не видит.
    inside_schema = False

    def needs_prefix(self, context):
        """Нужен ли объекту префикс. Самостоятельным — всегда, если о приставке
        есть соглашение: без него проверять нечего."""
        return bool(self.prefix)

    def _common(self, spec, context=None):
        found = []
        unknown = [f for f in spec.fields if f not in self.fields]
        if unknown:
            found.append(Finding(
                "МД-ПОЛЕ-НЕИЗВЕСТНО",
                про_неизвестные_поля(unknown, self.fields, self.name)))
            # Дальше не идём: остальные проверки читают поля, которых
            # инструмент не понял, и говорят о следствиях. Значение
            # перечисления, написанное как объект (`{"вид": …, "поля": …}`),
            # дало бы три находки на одну ошибку — незнакомые поля, пустое имя
            # и отсутствующий синоним, — и чинить тянуло бы все три.
            return found + self._name_findings(spec, context)
        for field in self.required:
            value = spec.get(field)
            if value is None or value == "" or value == []:
                found.append(Finding(
                    "МД-ПОЛЕ-ПУСТО", "поле обязательно и не заполнено", field))
        if "синоним" in self.fields and not spec.get("синоним"):
            # «Вместе с префиксом» — только когда он у имени есть: у
            # реквизитов `Комментарий`, `Сумма`, `Лимит` префикса нет, и такая
            # приписка отправила бы перечитывать правило про префиксы.
            имя = spec.get("имя") or ""
            found.append(Finding(
                "МД-БЕЗ-СИНОНИМА",
                f"синоним не задан — в интерфейсе будет видно имя «{имя}»"
                + (" вместе с префиксом" if self.соглашения.своё(имя) else ""),
                "синоним", Finding.WARNING))
        return found + self._name_findings(spec, context)

    def _name_findings(self, spec, context=None):
        """Проверки имени. Вынесены, чтобы работать и при непонятых полях:
        имя — единственное, о чём тогда есть смысл говорить."""
        found = []
        name = spec.get("имя")
        if name:
            if not NAME_RE.match(name):
                found.append(Finding(
                    "МД-ИМЯ-НЕДОПУСТИМО",
                    f"«{name}» не является именем объекта метаданных: "
                    + почему_имя_плохое(name), "имя"))
            elif self.needs_prefix(context) and not self.соглашения.своё(name):
                found.append(Finding(
                    "МД-ПРЕФИКС",
                    f"имя «{name}» без префикса «{self.prefix}» "
                    f"{_lookalike(name, self.prefix)}", "имя"))
            # Стандарт, а не догадка: #std474 п. 2.3 — не длиннее 80, и самое
            # длинное имя замеренной конфигурации ровно такое (22 292 объекта).
            # Ошибка, а не предупреждение: предупреждением оно записывалось
            # бы через «принято».
            if name and len(name) > self.LONGEST_MEASURED_NAME:
                роль = spec.kind == "Роль" and atomic_roles.is_atomic_role(
                    self.соглашения.атомарные_роли, name)
                found.append(Finding(
                    "МД-ИМЯ-ДЛИННОЕ",
                    f"имя длиной {len(name)} — длиннее {self.LONGEST_MEASURED_NAME} "
                    "символов (#std474 п. 2.3)"
                    + ("; имя роли строится из имени объекта — задайте в пункте "
                       "«сокращение» короткое имя объекта для имён ролей" if роль else ""),
                    "имя"))
        # #std474 — про метаданные; у частей схемы компоновки имена свои
        if not self.inside_schema:
            found.extend(_буква_ё(spec))
        return found


