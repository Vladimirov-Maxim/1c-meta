#: Латинские буквы, неотличимые на глаз от кириллических. Имя с такой
#: подменой выглядит правильным, и отказ «без префикса» читается как поломка
#: инструмента: человек видит два одинаковых слова.
LOOKALIKE = {
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "y": "у", "x": "х",
    "k": "к", "m": "м", "t": "т",
    "A": "А", "E": "Е", "O": "О", "P": "Р", "C": "С", "T": "Т", "H": "Н",
    "K": "К", "M": "М", "B": "В", "X": "Х", "3": "З", "6": "б",
}


def _буква_ё(spec):
    """«ё» в имени, синониме, комментарии — то, что назвал человек.

    #std474 п. 4: в именах, синонимах и комментариях буква «ё» не
    используется. Без проверки синоним «…отчётов» проходил бы с «замечаний
    нет» и уходил бы ещё и в синонимы ролей. Только поля задания: чужое «ё»,
    которое правка не трогает, не повод отказать.
    """
    found = []
    for поле in ("имя", "синоним", "комментарий"):
        if поле not in spec.asked:
            continue
        значение = spec.get(поле)
        тексты = (list(значение.values()) if isinstance(значение, dict)
                  else [значение] if isinstance(значение, str) else [])
        for текст in тексты:
            if "ё" in текст or "Ё" in текст:
                исправлено = текст.replace("ё", "е").replace("Ё", "Е")
                found.append(Finding(
                    "МД-БУКВА-Ё",
                    f"в поле «{поле}» буква «ё»: «{текст}» — в именах, синонимах и "
                    f"комментариях её не используют (#std474 п. 4); напишите «{исправлено}»",
                    поле))
    return found


def _lookalike(name, prefix):
    """Приписка к отказу, если имя отличается от префикса только раскладкой.

    Отказ «имя «мoй_Хитрый» без префикса «мой_»» показывает человеку два
    визуально одинаковых слова, и читается это как поломка инструмента,
    а не как ошибка в имени. Место подмены приходится называть прямо.
    """
    beginning = name[:len(prefix)]
    if len(beginning) < len(prefix) or beginning == prefix:
        return ""
    подменены = [
        f"символ {i + 1}: «{было}» (латиница) вместо «{надо}»"
        for i, (было, надо) in enumerate(zip(beginning, prefix, strict=True))
        if было != надо and LOOKALIKE.get(было) == надо]
    if not подменены:
        return ""
    return ". На глаз не отличить — " + "; ".join(подменены)


