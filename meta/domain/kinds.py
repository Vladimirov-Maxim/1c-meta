class EventSubscriptionKind(Kind):
    """Подписка на событие.

    Инварианты здесь не выдуманы: три сняты с замеренной конфигурации
    (обработчик — всегда метод общего модуля, 639 из 639; событие и грань
    источника согласованы во всех 639), четвёртый — соглашение команды:
    подписка на собственный объект — лишнее звено, обработчику место в
    модуле самого объекта.
    """
    type_fields = {"источник": "объект"}
    name = "ПодпискаНаСобытие"
    fields = ("имя", "синоним", "комментарий", "источник", "событие", "обработчик")
    required = ("имя", "синоним", "источник", "событие", "обработчик")
    #: Грань источника согласуется с событием, число параметров обработчика —
    #: с событием и видом источника: правка любого из трёх задевает правило.
    RELATED = (("источник", "событие", "обработчик"),)

    def own_findings(self, spec, config, context=None):
        found = []
        found.extend(self._handler(spec, config))
        found.extend(self._source_and_event(spec, config))
        found.extend(self._source_exists(spec, config))
        found.extend(self._own_object(spec))
        return found

    def _source_exists(self, spec, config):
        """Объект-источник должен быть в конфигурации.

        Опечатка в имени иначе всплывёт только при загрузке в базу, то есть
        у человека, а не у инструмента. Набор типов («все документы») не именует
        объект и потому не проверяется.
        """
        found = []
        for vtype in spec.get("источник") or []:
            if vtype.name is None:
                continue
            if config.object_exists(vtype.kind, vtype.name) is False:
                found.append(Finding(
                    "ПОДПИСКА-ИСТОЧНИК-НЕТ",
                    f"источника «{vtype}» в конфигурации нет", "источник"))
        return found

    def _handler_arity(self, spec, config, module, method):
        """Число параметров обработчика против того, что задаёт событие.

        Событие само по себе числа не задаёт: `ПередЗаписью` у документа
        принимает четыре параметра, у справочника два, у набора записей
        регистра три. Ключ — сочетание события, вида источника и грани,
        и таблица снята с 639 подписок замеренной конфигурации.

        Предупреждение, а не отказ: единичные расхождения в замеренной
        конфигурации есть, и объявлять их ошибкой значило бы спорить с
        вендорским кодом. Но отличие от 73 случаев из 77 стоит того, чтобы о
        нём сказать.
        """
        event = spec.get("событие")
        sources = spec.get("источник") or []
        if not event or len(sources) != 1 or sources[0].name is None:
            return []                       # набор типов сигнатуры не задаёт
        source = sources[0]
        expected = HANDLER_ARITY.get((event, source.kind, source.facet))
        if expected is None:
            return []                       # сочетание не замерено — молчим
        actual = config.handler_arity(module, method)
        if actual is None or actual == expected[0]:
            return []
        return [Finding(
            "ПОДПИСКА-СИГНАТУРА",
            f"у «{module}.{method}» параметров {actual}, а событие «{event}» у источника «{source.kind}» "
            f"принимает {expected[0]} — так в замеренной крупной типовой конфигурации у "
            f"{expected[1]} подписок из {expected[2]}",
            "обработчик", Finding.WARNING)]

    def _handler(self, spec, config):
        handler = spec.get("обработчик")
        if not handler:
            return []
        pieces = handler.split(".")
        if len(pieces) != 2:
            return [Finding(
                "ПОДПИСКА-ОБРАБОТЧИК-ФОРМА",
                f"обработчик задаётся как «ОбщийМодуль.Метод», получено «{handler}»",
                "обработчик")]
        module, method = pieces
        found = []
        if config.common_module_exists(module) is False:
            found.append(Finding(
                "ПОДПИСКА-МОДУЛЬ-НЕТ",
                f"общего модуля «{module}» в конфигурации нет — объекты "
                "одного задания друг друга не видят, заведите модуль "
                "отдельным заданием и с текстом обработчика", "обработчик"))
            return found
        exported = config.method_is_exported(module, method)
        if exported is False:
            found.append(Finding(
                "ПОДПИСКА-МЕТОД-НЕТ",
                f"в модуле «{module}» нет экспортного метода «{method}»",
                "обработчик"))
        elif exported is None:
            found.append(Finding(
                "ПОДПИСКА-МЕТОД-НЕПРОВЕРЕН",
                f"не удалось проверить метод «{module}.{method}» — посмотрите глазами",
                "обработчик", Finding.WARNING))
        else:
            found.extend(self._handler_arity(spec, config, module, method))
        return found

    def _source_and_event(self, spec, config):
        event = spec.get("событие")
        if not event:
            return []
        allowed = EVENTS.get(event)
        if allowed is None:
            return [Finding(
                "ПОДПИСКА-СОБЫТИЕ-НЕИЗВЕСТНО",
                f"событие «{event}» не встречается в замеренной крупной типовой конфигурации; "
                "если оно настоящее — "
                "пополните таблицу EVENTS, сверившись с синтакс-помощником",
                "событие")]
        found = []
        for vtype in spec.get("источник") or []:
            facets = [vtype.facet]
            if vtype.facet is None:
                # Определяемый тип сам раскрывается в набор типов — спросим мир.
                facets = config.defined_type_facets(vtype.name)
                if not facets:
                    found.append(Finding(
                        "ПОДПИСКА-ТИП-НЕ-РАСКРЫТ",
                        f"источник — определяемый тип «{vtype.name}»; согласованность с событием "
                        f"«{event}» не проверена",
                        "источник", Finding.WARNING))
                    continue
            for facet in facets:
                if facet not in allowed:
                    found.append(Finding(
                        "ПОДПИСКА-СОБЫТИЕ-ГРАНЬ",
                        f"событие «{event}» не бывает у грани «{facet}» "
                        f"({vtype}); допустимы: {', '.join(allowed)}",
                        "событие"))
        return found

    def _own_object(self, spec):
        if not self.prefix:
            return []
        own = [str(t) for t in (spec.get("источник") or [])
                if t.name and self.соглашения.своё(t.name)]
        if not own:
            return []
        return [Finding(
            "ПОДПИСКА-НА-СВОЙ-ОБЪЕКТ",
            "источник — собственный объект ({}): обработчику место в модуле самого "
            "объекта, подписка здесь лишнее звено".format(", ".join(own)),
            "источник", Finding.WARNING)]


class CommonModuleKind(Kind):
    """Общий модуль.

    Контекст модуля задаёт постфикс его имени — так устроен стандарт #469
    «Правила создания общих модулей», и так же устроена замеренная
    конфигурация: `ВызовСервера` → «сервер + вызов сервера» у 439 модулей из
    455, `КлиентСервер` → все четыре контекста у 466 из 475, `Клиент` → оба
    клиента у 631 из 636, `Глобальный` → клиент + глобальный у 56 из 58,
    `ПовтИсп` → «на время сеанса» у 205 из 222 (замер по 4103 модулям
    корпуса). Поэтому умолчания выводятся из имени, а не одни на всех:
    умолчания серверного модуля, подставленные в `…ВызовСервера`, дали бы
    редкое сочетание, о котором инструмент сам же и предупредил бы.

    Отклонение имени от флагов — отказ там, где стандарт говорит «обязательно»
    (постфикс `ВызовСервера` ⇔ флаг «вызов сервера», `Глобальный` ⇔ флаг
    «глобальный», клиентское имя без клиентского контекста), и предупреждение
    там, где он рекомендует (состав контекстов, `ПовтИсп`, `ПолныеПрава`).
    Названное человеком явно не переписывается никогда.

    Инварианты про сочетания флагов сняты с тех же карточек: «вызов сервера»,
    «внешнее соединение» и «привилегированный» без «сервер» — 0 случаев.
    """

    name = "ОбщийМодуль"
    fields = ("имя", "синоним", "комментарий", "глобальный",
              "клиентУправляемоеПриложение", "сервер", "внешнееСоединение",
              "клиентОбычноеПриложение", "вызовСервера", "привилегированный",
              "повторноеИспользование", "текст")
    required = ("имя",)
    #: Умолчания серверного модуля — того, что без постфикса. Остальные
    #: постфиксы правят их в `fill`; справка `--поля` печатает эти и говорит,
    #: что они зависят от имени.
    defaults = {
        "синоним": "",
        "комментарий": "",
        "глобальный": False,
        "клиентУправляемоеПриложение": False,
        "сервер": True,
        "внешнееСоединение": True,
        "клиентОбычноеПриложение": True,
        "вызовСервера": False,
        "привилегированный": False,
        "повторноеИспользование": "НеИспользовать",
        "текст": "",
    }

    # флаг → от какого флага он зависит; нарушений в корпусе: 0 на каждое
    NEED_SERVER = ("вызовСервера", "внешнееСоединение", "привилегированный")
    CONTEXTS = ("сервер", "внешнееСоединение",
                "клиентУправляемоеПриложение", "клиентОбычноеПриложение")
    #: Все флаги контекста, которые стандарт задаёт постфиксом.
    CONTEXT_FLAGS = ("глобальный", "клиентУправляемоеПриложение", "сервер",
                     "внешнееСоединение", "клиентОбычноеПриложение", "вызовСервера")

    #: Стандарт #469, п. 1.2 и 3.2.1: базовый постфикс -> включённые флаги.
    #: Пустой постфикс — серверный модуль (п. 2.1: постфикс `Сервер` допустим,
    #: но не обязателен).
    CONTEXT_BY_POSTFIX = {
        "": ("сервер", "внешнееСоединение", "клиентОбычноеПриложение"),
        "Сервер": ("сервер", "внешнееСоединение", "клиентОбычноеПриложение"),
        "ВызовСервера": ("сервер", "вызовСервера"),
        "Клиент": ("клиентУправляемоеПриложение", "клиентОбычноеПриложение"),
        "КлиентСервер": ("клиентУправляемоеПриложение", "сервер",
                         "внешнееСоединение", "клиентОбычноеПриложение"),
        "Глобальный": ("глобальный", "клиентУправляемоеПриложение",
                       "клиентОбычноеПриложение"),
    }
    #: Уточняющие постфиксы (п. 3.2): стоят после базового и добавляют
    #: по одному свойству. `Переопределяемый` свойств не меняет.
    REFINEMENTS = ("ПовтИсп", "ПолныеПрава", "Переопределяемый")
    #: `ПовтИсп` без значения — «на время сеанса»: 205 модулей из 222.
    REUSE_DEFAULT = "НаВремяСеанса"

    @classmethod
    def разобрать_имя(cls, name):
        """Имя -> (базовый постфикс, уточнения). «Клиент» у `…КлиентПовтИсп` виден.

        Уточнения снимаются с хвоста по одному: `…СлужебныйПолныеПрава` — это
        серверный модуль с привилегиями, `…КлиентПовтИсп` — клиентский
        с повторным использованием.
        """
        уточнения = []
        остаток = name
        снято = True
        while снято:
            снято = False
            for хвост in cls.REFINEMENTS:
                if остаток.endswith(хвост) and хвост not in уточнения:
                    уточнения.append(хвост)
                    остаток = остаток[:-len(хвост)]
                    снято = True
        # от длинного к короткому: «ВызовСервера» кончается на «Сервера», не «Сервер»,
        # но «КлиентСервер» кончается и на «Сервер»
        for постфикс in ("ВызовСервера", "КлиентСервер", "Глобальный", "Клиент", "Сервер"):
            if остаток.endswith(постфикс):
                return постфикс, уточнения
        return "", уточнения

    def fill(self, spec, context=None):
        """Умолчания контекстов — по постфиксу имени (стандарт #469).

        Заполняется только не названное: явное «внешнееСоединение: true»
        рядом с `…ВызовСервера` остаётся и получает замечание в проверке.
        """
        filled = Kind.fill(self, spec, context)
        постфикс, уточнения = self.разобрать_имя(spec.get("имя") or "")
        включено = self.CONTEXT_BY_POSTFIX[постфикс]
        for flag in self.CONTEXT_FLAGS:
            if flag not in spec.fields:
                filled.fields[flag] = flag in включено
        if "ПовтИсп" in уточнения and "повторноеИспользование" not in spec.fields:
            filled.fields["повторноеИспользование"] = self.REUSE_DEFAULT
        if "ПолныеПрава" in уточнения and "привилегированный" not in spec.fields:
            filled.fields["привилегированный"] = True
        return filled

    def own_findings(self, spec, config, context=None):
        found = []
        name = spec.get("имя") or ""
        постфикс, уточнения = self.разобрать_имя(name)
        включено = set(self.CONTEXT_BY_POSTFIX[постфикс])

        # --- имя и флаги обязаны сходиться там, где стандарт говорит «обязательно»
        if spec.get("вызовСервера") and постфикс != "ВызовСервера":
            found.append(Finding(
                "МОДУЛЬ-ВЫЗОВ-БЕЗ-ПОСТФИКСА",
                "флаг «вызов сервера» взведён, а имя не кончается на «ВызовСервера» — "
                "стандарт #469 п. 2.2 требует этот постфикс обязательно",
                "имя"))
        if постфикс == "ВызовСервера" and not spec.get("вызовСервера"):
            found.append(Finding(
                "МОДУЛЬ-ИМЯ-ВЫЗОВ-СЕРВЕРА",
                "имя обещает вызов сервера, а флаг выключен явно "
                "(в замеренной крупной типовой конфигурации таких расхождений нет ни одного)",
                "вызовСервера"))
        if spec.get("глобальный") and постфикс != "Глобальный":
            found.append(Finding(
                "МОДУЛЬ-ГЛОБАЛЬНЫЙ-БЕЗ-ПОСТФИКСА",
                "флаг «глобальный» взведён, а имя не кончается на «Глобальный» "
                "(стандарт #469 п. 3.2.1; постфикс «Клиент» при этом не добавляется)",
                "имя"))
        if постфикс == "Глобальный" and not spec.get("глобальный"):
            found.append(Finding(
                "МОДУЛЬ-ИМЯ-ГЛОБАЛЬНЫЙ",
                "имя обещает глобальный модуль, а флаг выключен явно", "глобальный"))
        if (постфикс in ("Клиент", "КлиентСервер", "Глобальный")
                and not spec.get("клиентУправляемоеПриложение")):
            found.append(Finding(
                "МОДУЛЬ-КЛИЕНТ-БЕЗ-КЛИЕНТА",
                f"имя с постфиксом «{постфикс}» обещает клиентский контекст, "
                "а «клиент (управляемое приложение)» выключен явно (стандарт #469 п. 2.3)",
                "клиентУправляемоеПриложение"))
        if постфикс == "Клиент" and spec.get("сервер"):
            found.append(Finding(
                "МОДУЛЬ-КЛИЕНТ-С-СЕРВЕРОМ",
                "имя с постфиксом «Клиент» и включённый «сервер» — это клиент-серверный "
                "модуль, постфикс у него «КлиентСервер» (стандарт #469 п. 2.4)", "сервер"))

        # --- рекомендации стандарта: отклонение допустимо, но названо
        лишние = [f for f in self.CONTEXT_FLAGS if spec.get(f) and f not in включено]
        недостающие = [f for f in включено if not spec.get(f)]
        if (лишние or недостающие) and not any(
                f.code in ("МОДУЛЬ-ВЫЗОВ-БЕЗ-ПОСТФИКСА", "МОДУЛЬ-ГЛОБАЛЬНЫЙ-БЕЗ-ПОСТФИКСА",
                           "МОДУЛЬ-КЛИЕНТ-БЕЗ-КЛИЕНТА", "МОДУЛЬ-КЛИЕНТ-С-СЕРВЕРОМ")
                for f in found):
            что = []
            if лишние:
                что.append("лишние: " + ", ".join(лишние))
            if недостающие:
                что.append("выключены: " + ", ".join(недостающие))
            found.append(Finding(
                "МОДУЛЬ-КОНТЕКСТ-НЕ-ПО-СТАНДАРТУ",
                "контекст отличается от стандарта #469 для постфикса «{}» ({}); "
                "такие модули встречаются, но проверьте, что это намеренно".format(
                    постфикс or "без постфикса", "; ".join(что)),
                (лишние or недостающие)[0], Finding.WARNING))
        повтор = spec.get("повторноеИспользование")
        if "ПовтИсп" in уточнения and повтор == "НеИспользовать":
            found.append(Finding(
                "МОДУЛЬ-ПОВТИСП-БЕЗ-ФЛАГА",
                "имя с постфиксом «ПовтИсп», а повторное использование выключено явно "
                "(стандарт #469 п. 3.2.3; в замеренной крупной типовой конфигурации так "
                "лишь у 2 модулей из 257)",
                "повторноеИспользование", Finding.WARNING))
        if повтор in RETURN_REUSE_VALUES[1:] and "ПовтИсп" not in уточнения:
            found.append(Finding(
                "МОДУЛЬ-ПОВТИСП-БЕЗ-ПОСТФИКСА",
                "повторное использование включено, а имя без постфикса «ПовтИсп» "
                "(«КлиентПовтИсп» у клиентского) — стандарт #469 п. 3.2.3",
                "имя", Finding.WARNING))
        if spec.get("привилегированный") and "ПолныеПрава" not in уточнения:
            found.append(Finding(
                "МОДУЛЬ-ПРИВИЛЕГИРОВАННЫЙ-БЕЗ-ПОСТФИКСА",
                "флаг «привилегированный» взведён, а имя без постфикса «ПолныеПрава» "
                "(стандарт #469 п. 3.2.2; в замеренной крупной типовой конфигурации так у 45 "
                "из 47 привилегированных, то есть постфикс почти не используют — "
                "рекомендация, не запрет)",
                "имя", Finding.WARNING))

        # --- сочетания флагов, которых не бывает
        for flag in self.NEED_SERVER:
            if spec.get(flag) and not spec.get("сервер"):
                found.append(Finding(
                    "МОДУЛЬ-БЕЗ-СЕРВЕРА",
                    f"флаг «{flag}» не бывает без «сервер» (в замеренной крупной типовой "
                    "конфигурации — 0 таких из 4100)", flag))
        if spec.get("вызовСервера") and spec.get("глобальный"):
            found.append(Finding(
                "МОДУЛЬ-ГЛОБАЛЬНЫЙ-ВЫЗОВ",
                "глобальный модуль не бывает вызовом сервера", "глобальный"))
        if not any(spec.get(d) for d in self.CONTEXTS):
            found.append(Finding(
                "МОДУЛЬ-БЕЗ-КОНТЕКСТА",
                "не задан ни один контекст: модуль не будет доступен ниоткуда",
                "сервер"))
        if повтор not in RETURN_REUSE_VALUES:
            found.append(Finding(
                "МОДУЛЬ-ПОВТОРНОЕ-ИСПОЛЬЗОВАНИЕ",
                f"«{повтор}» — не значение повторного использования; допустимы: "
                f"{', '.join(RETURN_REUSE_VALUES)}",
                "повторноеИспользование"))
        return found


RETURN_REUSE_VALUES = ("НеИспользовать", "НаВремяВызова", "НаВремяСеанса")


class NestedKind(Kind):
    """Сущность, живущая узлом внутри чужой карточки.

    Общее у реквизита, измерения, ресурса и значения перечисления: правило
    префикса зависит от хозяина, а состав свойств замерен не у всех видов
    хозяев — про незамеренные надо честно сказать, а не молча написать файл.
    """

    #: виды объектов-хозяев, у которых состав свойств замерен
    HOSTS = ()
    #: код замечания о незамеренном виде хозяина
    HOST_FINDING = None
    #: свойство -> виды хозяев, у которых оно бывает (пусто — бывает у всех)
    APPLIES_TO = {}
    #: код замечания о заданном свойстве, которого у хозяина нет
    APPLIES_FINDING = "РЕКВИЗИТ-ПОЛЕ-НЕ-ДЛЯ-ВИДА"

    def needs_prefix(self, context):
        """Префикс нужен только в чужом объекте.

        Правило говорит о «типовых объектах» — то есть о чужих; внутри своего
        объекта коллизии с вендором не бывает, и в своих объектах реквизиты
        обычно называют без префикса.

        Правило смотрит на имя хозяина независимо от того, существует он уже
        или создаётся этим же заданием: объект без префикса чужой в обоих
        случаях, а собственный объект обязан быть с префиксом по своему же
        правилу — и это проверяется, а не подразумевается.
        """
        owner = Host.of(context).owner_name
        if owner is None or not self.prefix:
            return False
        return not owner.startswith(self.prefix)

    def host_findings(self, context):
        host_kind = Host.of(context).kind
        if not host_kind or host_kind in self.HOSTS:
            return []
        # «Не замерен» читалось бы как «может и бывает, просто не проверяли»,
        # и пришлось бы выяснять, бывает ли у справочника измерение. Сказано
        # то, что есть на самом деле: инструмент такого сочетания не описывает,
        # а вот у кого оно описано — вот эти виды.
        return [Finding(
            self.HOST_FINDING,
            f"«{self.name}» внутри вида «{host_kind}» инструмент не описывает; "
            f"описан{'о' if len(self.HOSTS) == 1 else 'ы'} у: "
            f"{', '.join(self.HOSTS)}")]

    def type_findings(self, spec, config):
        """Ссылочный тип должен указывать на существующий объект.

        Сам поиск — операция над файлами, и живёт он в инфраструктуре: домен
        только задаёт вопрос через порт `Configuration.object_exists`, а кто
        и как на него отвечает — не его дело.
        """
        if config is None or "тип" not in self.fields:
            return []
        value = spec.get("тип")
        found = []
        for one in (value if isinstance(value, list) else [value]):
            if not isinstance(one, TypeRef) or not one.name:
                continue
            if one.kind == "ОпределяемыйТип":
                continue                        # у него своя проверка граней
            exists = config.object_exists(one.kind, one.name)
            if exists is False:
                found.append(Finding(
                    "ТИП-НЕТ",
                    f"типа «{one.kind}.{one.name}» в конфигурации нет", "тип"))
            elif exists is None:
                found.append(Finding(
                    "ТИП-НЕПРОВЕРЕН",
                    f"существование «{one.kind}.{one.name}» проверить нечем — "
                    "посмотрите глазами", "тип", Finding.WARNING))
        return found + self.qualifier_findings(spec)

    def qualifier_findings(self, spec):
        """Числа в квалификаторе типа: платформа их не отвергает, а подменяет.

        Без этой проверки `Число(0.5)`, `Строка(-5)` и `Число(999.2)`
        уходили бы в файл с вердиктом «замечаний нет». Опыт на пустой
        конфигурации показывает, что происходит дальше: разрядность 39
        становится 38, дробная часть 5 при разрядности 0 — нулём, длина −5
        читается как 4294967291. Загрузка при этом успешна — то есть человек
        уверен, что записал заказанное.
        """
        if "тип" not in self.fields:
            return []
        value = spec.get("тип")
        found = []
        for one in (value if isinstance(value, list) else [value]):
            if isinstance(one, StringType):
                found.extend(self._string_bounds(one))
            elif isinstance(one, NumberType):
                found.extend(self._number_bounds(one))
        return found

    @staticmethod
    def _string_bounds(one):
        if one.length is None or one.length >= 0:
            return []
        return [Finding(
            "ТИП-ДЛИНА",
            f"длина строки {one.length} отрицательна; платформа читает её "
            "как беззнаковое число и записывает 4294967291, а загрузка при "
            "этом проходит", "тип")]

    @staticmethod
    def _number_bounds(one):
        found = []
        digits, fraction = one.digits, one.fraction_digits
        if digits is not None and digits < 0:
            found.append(Finding("ТИП-РАЗРЯДНОСТЬ",
                                 f"разрядность {digits} отрицательна", "тип"))
        elif digits is not None and digits > MAX_DIGITS:
            found.append(Finding(
                "ТИП-РАЗРЯДНОСТЬ",
                f"разрядность {digits} больше {MAX_DIGITS}; платформа молча "
                f"срежет до {MAX_DIGITS}", "тип"))
        if fraction is not None and fraction < 0:
            found.append(Finding("ТИП-ДРОБНАЯ",
                                 f"дробная часть {fraction} отрицательна", "тип"))
        elif (fraction is not None and digits is not None and fraction > digits):
            found.append(Finding(
                "ТИП-ДРОБНАЯ",
                f"дробная часть {fraction} больше разрядности {digits}; "
                "платформа молча обнулит дробную часть", "тип"))
        return found

    def fill(self, spec, context=None):
        """Умолчания свойств, которых у хозяина нет, не подставляются.

        Иначе инструмент отверг бы задание из-за значения, которое сочинил
        сам: строковому реквизиту ставится значение заполнения, а у реквизита
        табличной части такого свойства нет — и самый обычный случай
        (строковая колонка) не создавался бы вовсе.
        """
        filled = Kind.fill(self, spec, context)
        host_kind = Host.of(context).kind
        if host_kind:
            for field, kinds in self.APPLIES_TO.items():
                if host_kind not in kinds and field not in spec.fields:
                    filled.fields.pop(field, None)
        # Строковому — пустое значение заполнения. Правило одно на все
        # вложенные виды и потому живёт здесь, а не тремя экземплярами у
        # реквизита, измерения и ресурса: из трёх мест забыть одно проще, чем
        # помнить все.
        if ("значениеЗаполнения" in filled.fields
                and "значениеЗаполнения" not in spec.fields
                and isinstance(filled.get("тип"), StringType)):
            filled.fields["значениеЗаполнения"] = ""
        return filled

    def applicability_findings(self, spec, context=None):
        """Заданное свойство, которого у этого хозяина не бывает.

        Молчать здесь нельзя: значение из задания не попадёт в файл, и человек
        об этом не узнает. Проверка общая для всех вложенных видов: правило
        держится механизмом, а не экземпляром у каждого вида.
        """
        host_kind = Host.of(context).kind
        if not host_kind:
            return []
        return [Finding(
            self.APPLIES_FINDING,
            "у вида «{}» свойства «{}» нет — значение будет отброшено; "
            "оно бывает у: {}".format(host_kind, field, ", ".join(kinds)), field)
            for field, kinds in self.APPLIES_TO.items()
            if host_kind not in kinds and field in spec.fields
            and spec.fields[field] != self.defaults.get(field)]

    #: код замечания «у хозяина такое имя уже занято»
    TAKEN_FINDING = "ВЛОЖЕННОЕ-ИМЯ-ЗАНЯТО"
    #: код замечания «состав хозяина прочитать не удалось»
    UNKNOWN_FINDING = "ВЛОЖЕННОЕ-СОСТАВ-НЕПРОВЕРЕН"
    #: код замечания «хозяина нет в конфигурации»
    NO_HOST_FINDING = "ВЛОЖЕННОЕ-ХОЗЯИНА-НЕТ"

    def own_findings(self, spec, config, context=None):
        """Инварианты вложенной сущности, общие для всех её видов.

        Переопределять этот метод, не вызвав его, — потеря общих правил
        молча. Подкласс добавляет своё к результату, а не пишет свой набор.
        """
        found = self.host_findings(context)
        if found:
            return found                      # вид хозяина не замерен — дальше некуда
        found.extend(self.standard_name_findings(spec, context))
        found.extend(self.applicability_findings(spec, context))
        found.extend(self.occupancy_findings(spec, config, context))
        # Проверка типа общая для всех вложенных: у измерения и ресурса тип
        # тоже есть, и опечатка в имени справочника не должна проходить
        # молча — «замечаний нет» на несуществующий справочник. Участвует
        # вид или нет, решает состав его полей.
        found.extend(self.type_findings(spec, config))
        return found

    def standard_name_findings(self, spec, context=None):
        """Имя, которое платформа занимает сама.

        Стандартные реквизиты вида среди детей не лежат: платформа заводит их
        сама и в выгрузку не выписывает, пока их не настроят руками. Спросить
        про них состав детей нельзя — нужна таблица.

        Проверка смотрит на **вид** хозяина, а не на его адрес, и потому
        работает и когда хозяина ещё нет на диске. В проверке занятости — а
        та у несуществующего хозяина выходит сразу — измерение «Период»
        проходило бы именно на главном пути: регистр, заведённый сразу с
        измерениями, писался бы со словами «замечаний нет».

        Это ошибка, а не предупреждение: платформа отвергает загрузку словами
        «Недопустимое имя измерения - Период», и отвергает у периодического
        регистра и у непериодического одинаково (опыт на пустой конфигурации). Здесь
        не «в выгрузке не встречается», а «проверено платформой».
        """
        host_kind = Host.of(context).kind
        name = spec.get("имя")
        standard = STANDARD_ATTRIBUTES_RU.get(host_kind, ())
        if not name or name not in standard:
            return []
        return [Finding(
            "ВЛОЖЕННОЕ-ИМЯ-СТАНДАРТНОЕ",
            f"«{name}» — стандартный реквизит вида «{host_kind}», это имя "
            f"платформа занимает сама и загрузку отвергает; стандартные: "
            f"{', '.join(standard)}", "имя")]

    def occupancy_findings(self, spec, config, context=None):
        """Хозяин существует, и имя внутри него свободно.

        Занятость спрашивается про всех детей, а не про свой вид: у платформы
        имена детей объекта — одно пространство. Спрашивай про свой вид,
        измерение и ресурс с одним именем добавлялись бы в регистр по очереди
        без единого замечания, а конфигурация с таким регистром не грузится.
        """
        host = Host.of(context)
        address = host.path or (
            ((host.kind, host.name),) if host.kind and host.name else ())
        if not (host.exists and address):
            return []
        found = []
        where = ".".join(f"{kind}.{name_}" for kind, name_ in address)
        if config.object_exists(*address[0]) is False:
            return [Finding(
                self.NO_HOST_FINDING,
                "объекта «{}.{}» в конфигурации нет".format(*address[0]))]
        name = spec.get("имя")
        taken = config.taken_names(address)
        if taken is None:
            found.append(Finding(
                self.UNKNOWN_FINDING,
                f"не удалось прочитать состав «{where}» — "
                "имя на занятость не проверено", "имя", Finding.WARNING))
        elif name in taken:
            found.append(Finding(
                self.TAKEN_FINDING,
                f"у «{where}» имя «{name}» уже занято", "имя"))
        return found


class AttributeKind(NestedKind):
    """Реквизит объекта.

    Не самостоятельный объект: карточки у него нет, он живёт узлом внутри чужой.
    Домену эта разница не видна — он так же называет поля и проверяет правила,
    а файл это будет или узел, решает перекладка.

    Умолчания сняты с 27 548 реквизитов замеренной конфигурации: это то, что пишет
    конфигуратор у только что созданного реквизита.
    """
    type_fields = {"тип": "значение"}
    name = "Реквизит"
    fields = ("имя", "синоним", "комментарий", "тип", "режимПароля", "формат",
              "форматРедактирования", "подсказка", "выделятьОтрицательные", "маска",
              "многострочный", "расширенноеРедактирование", "минимальноеЗначение",
              "максимальноеЗначение", "заполнятьИзДанныхЗаполнения",
              "значениеЗаполнения", "проверкаЗаполнения", "выборГруппИЭлементов",
              "связиПараметровВыбора", "параметрыВыбора", "быстрыйВыбор",
              "созданиеПриВводе", "формаВыбора", "связьПоТипу",
              "историяВыбораПриВводе", "использование", "индексирование",
              "полнотекстовыйПоиск", "историяДанных")
    required = ("имя", "тип")
