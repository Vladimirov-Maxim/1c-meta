# ruff: noqa: F811 — фикстура `репо` взята из test_code и принимается параметром
"""Раскладка вставок там, где шаблон с пустыми строками неуместен.

Текст запроса: метки — строки-комментарии
BSL вплотную к строкам литерала, пустая строка без `|` внутри литерала
недопустима — ни снаружи меток, ни внутри ИЗМЕНЕН.

Смена сигнатуры: ИЗМЕНЕН оборачивает только объявление —
метка вплотную под описанием метода (пустая строка отрывала бы описание),
внутри вставки и под закрывающей меткой пустых строк нет (они оказались
бы в теле метода). Проверка правок записанное принимает без находок.
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

from meta import add  # noqa: E402

from .test_code import ВЕНДОРСКИЙ, запустить, одна, правка, прочитать, репо  # noqa: E402,F401

ОТКРЫТА = "// {[+](фрагмент ДОБАВЛЕН), 31.08.2026, #TEAM Петров Петр #TASK-1"
ИЗМЕНЕН = "// {[*](фрагмент ИЗМЕНЕН), 31.08.2026, #TEAM Петров Петр #TASK-1"
ЗАКРЫТА = "// } Петров Петр, 31.08.2026"

ЗАПРОС = ["Функция Данные()", "\tЗапрос = Новый Запрос;", "\tЗапрос.Текст =", "\t\"ВЫБРАТЬ",
          "\t|\tТ.Номер,", "\t|\tТ.Сумма", "\t|ИЗ", "\t|\tДокумент.Т КАК Т\";", "\tВозврат Запрос;",
          "КонецФункции"]

СИГНАТУРА = ["// Выгружает данные.", "//", "// Параметры:", "//  Каталог - Строка - куда.", "//",
             "Функция Выгрузить(Каталог) Экспорт", "\t", "\tВозврат Каталог;", "", "КонецФункции"]


def находки(root):
    ответ = os.path.join(os.path.dirname(root), "ответ.json")
    add.main(["--проверить", root, "--задача", "TASK-1", "--json", ответ])
    return [f["код"] for f in json.load(open(ответ, encoding="utf-8"))["находки"]]


def test_an_added_query_line_has_no_blank_lines_around_its_markers(репо):
    root = репо(ЗАПРОС)
    код, текст = запустить(root, path=ВЕНДОРСКИЙ, edits=[правка(6, code="\t|\tТ.Дата,")])
    assert код == 0, текст
    строки = прочитать(root, ВЕНДОРСКИЙ)[0]
    assert строки[3:9] == ["\t\"ВЫБРАТЬ", "\t|\tТ.Номер,", "\t" + ОТКРЫТА, "\t|\tТ.Дата,", "\t" + ЗАКРЫТА,
                           "\t|\tТ.Сумма"]


def test_a_changed_query_line_has_no_blank_lines_inside_the_insertion(репо):
    root = репо(ЗАПРОС)
    код, текст = запустить(root, path=ВЕНДОРСКИЙ, edits=[одна("\t|\tТ.Сумма", "\t|\tТ.Сумма КАК Итого") | {"line": 6}])
    assert код == 0, текст
    строки = прочитать(root, ВЕНДОРСКИЙ)[0]
    assert строки[4:10] == ["\t|\tТ.Номер,", "\t" + ИЗМЕНЕН, "\t//|\tТ.Сумма", "\t|\tТ.Сумма КАК Итого",
                            "\t" + ЗАКРЫТА, "\t|ИЗ"]


def test_a_signature_change_wraps_only_the_declaration_under_its_description(репо):
    root = репо(СИГНАТУРА)
    код, текст = запустить(root, path=ВЕНДОРСКИЙ, edits=[
        одна("Функция Выгрузить(Каталог) Экспорт", "Функция Выгрузить(Каталог, Период = Неопределено) Экспорт")
        | {"line": 6}])
    assert код == 0, текст
    строки = прочитать(root, ВЕНДОРСКИЙ)[0]
    assert строки[4:10] == ["//", ИЗМЕНЕН, "//Функция Выгрузить(Каталог) Экспорт",
                            "Функция Выгрузить(Каталог, Период = Неопределено) Экспорт", ЗАКРЫТА, "\t"]
    assert находки(root) == []


def test_a_continued_expression_does_not_warn_about_a_lost_tab():
    """Вызов с продолжением на следующих строках отступает глубже начала — это
    не потерянный таб; блок, начатый и законченный на разных уровнях, — да."""
    from meta.domain.edits import indent_warning
    assert indent_warning(["\tЗначение = ?(Строка = Неопределено,", "\t\tСтр.Статья,",
                           "\t\tСтрока.Статья);"], "\t") == ""
    assert "разных отступах" in indent_warning(["\tА = 1;", "\t\tБ = 2;"], "\t")
    assert indent_warning(["\tА = \"(\";  // (", "\t\tБ = 2;"], "\t")    # скобки в литерале не в счёт


def test_a_placeholder_in_a_comment_is_not_refused():
    from meta.domain.edits import placeholder
    assert placeholder("// Заменяет <ИмяНастройки> именем настройки.") is None
    assert placeholder("Вызвать(<Модуль>);") == "<Модуль>"


def test_a_new_method_without_markers_is_separated_from_its_neighbours(репо):
    """Модуль, созданный задачей: метки не ставятся, но новый метод перед
    `#КонецОбласти`, стоящим вплотную к `КонецПроцедуры`, отделяется пустыми
    строками с обеих сторон."""
    import subprocess

    root = репо(["#Область Служебные", "Процедура Старая()", "КонецПроцедуры", "#КонецОбласти"])
    # модуль «создан задачей»: в базовой ревизии его нет
    subprocess.run(["git", "-C", root, "rm", "-q", "--cached", ВЕНДОРСКИЙ], check=True)
    subprocess.run(["git", "-C", root, "commit", "-q", "-m", "без модуля"], check=True)
    код, текст = запустить(root, path=ВЕНДОРСКИЙ, edits=[правка(4, code="Процедура Новая()\nКонецПроцедуры")])
    assert код == 0, текст
    assert прочитать(root, ВЕНДОРСКИЙ)[0] == ["#Область Служебные", "Процедура Старая()", "КонецПроцедуры", "",
                                               "Процедура Новая()", "КонецПроцедуры", "", "#КонецОбласти"]

