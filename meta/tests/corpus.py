"""Где лежит конфигурация, по которой сверяются тесты.

Инструмент от конкретного проекта не зависит, а его проверки — зависят: сила
сверки в том, что эталонов десятки тысяч и написала их платформа. Поэтому путь
к выгрузке задаётся снаружи и здесь только один раз.

Задаётся переменной окружения `META_CORPUS` — путь к каталогу выгрузки
(с `Configuration.xml`). Без неё тесты, которым нужна выгрузка, помечаются
пропущенными, а остальные идут как обычно.
"""

import os

CORPUS = os.environ.get("META_CORPUS", "")


def available():
    return bool(CORPUS) and os.path.isfile(os.path.join(CORPUS, "Configuration.xml"))
