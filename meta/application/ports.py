"""Интерфейсы, которые объявляет прикладной слой и реализует инфраструктура.

Зависимость направлена внутрь: не приложение знает про файлы и XML, а внешний
слой обязуется соблюдать этот договор. Поэтому интерфейсы лежат здесь, у того,
кто ими пользуется, а не там, где они исполняются.

Что это даёт на практике: вторая площадка — другой формат выгрузки (EDT),
другое хранилище (память в тестах, git-ветка, удалённая база) — это новая
реализация `Platform` и ни одной правки в сценариях. Проверяется это не
на словах: тесты подсовывают приложению собственную реализацию и убеждаются,
что оно работает, ни разу не коснувшись диска.

    Разбора дерева здесь нет намеренно: ни один сценарий не вызывает
    методов `CardTree` и не получает дерева. Шов «репозиторий ↔ разбор» —
    внутренний шов инфраструктуры, и держать его в прикладном слое значило
    бы заставлять `infra` импортировать `application`, а гард направления
    зависимостей — нести отдельное исключение. Договор живёт в
    `infra/tree.py`.
    """

from ..domain.model import Configuration


class Plan:
    """Подготовленные изменения, ещё не применённые.

    Разделение «подготовить» и «применить» — не удобство, а требование:
    просмотр обязан быть возможен без записи, а запись — целиком или никак.
    """

    def describe(self):
        """Человекочитаемый перечень того, что будет сделано."""
        raise NotImplementedError

    def contents(self):
        """[(путь, было, станет)] — тексты файлов до и после записи; `None` —
        файла нет (создаётся) или не будет (удаляется). Для подробного
        просмотра: размер файла не говорит, что именно в нём окажется."""
        raise NotImplementedError

    def apply(self):
        """Применить всё разом. Вернуть перечень изменённого."""
        raise NotImplementedError


class Platform(Configuration):
    """Целевая площадка: словарь её формата и её хранилище.

    Наследует `Configuration` — порт чтения, которым пользуется домен: площадка
    отвечает и на вопросы «есть ли такой модуль», «экспортный ли метод».
    Так у приложения одна зависимость вместо трёх.
    """

    def translate_card(self, spec, uuid, new_id=None):
        """Спецификация на языке домена -> карточка на языке площадки."""
        raise NotImplementedError

    def read_spec(self, path):
        """Адрес -> спецификация того, что лежит в выгрузке.

        Обратная сторона `translate_card`. Нужна затем же, зачем просмотр:
        ответить на вопрос «то ли записано, что задумано», — только про то,
        что уже на диске, а не про намерение. Без неё проверка записанного
        уходила бы из инструмента в чтение XML глазами.
        """
        raise NotImplementedError

    def prepare(self, cards):
        """Карточки -> `Plan`. Ничего не пишет."""
        raise NotImplementedError

    def translate_node_for(self, spec, uuid, host, owner=None, new_id=None):
        """Спецификация вложенной сущности -> узел для врезки в чужую карточку.

        `owner` и `new_id` нужны тем, у кого имя порождаемого типа составное:
        табличная часть зовётся `CatalogTabularSection.Справочник.ТЧ`.
        """
        raise NotImplementedError

    def prepare_changes(self, changes):
        """[(путь, поля)] -> `Plan` на правку свойств. Ничего не пишет.

        Путь — список пар «(доменный вид, имя)» от объекта вглубь; первая пара
        указывает карточку, остальные — вложенную сущность внутри неё.
        """
        raise NotImplementedError

    def prepare_deletion(self, paths):
        """[путь] -> `Plan` на удаление. Ничего не пишет.

        Путь из одной пары — объект целиком: карточка, файлы-спутники и запись
        в реестре конфигурации. Длиннее — вложенная сущность внутри карточки.
        """
        raise NotImplementedError

    def prepare_addition(self, additions):
        """[(адрес хозяина, узел, имя, вид, представление)] -> `Plan`.

        Ничего не пишет.

        Четвёрки, а не тройки: вид ребёнка нужен, чтобы найти его контейнеры
        и место в порядке детей. Договор обязан описывать то, что приходит на
        самом деле: иначе вторая площадка упала бы на распаковке, а подставная
        площадка в тестах, согласная с реализацией, а не с договором, этого не
        поймала бы.

        Узлы приходят готовыми: идентификаторы порождает сценарий, как и в
        остальных операциях, — инфраструктуре про них знать незачем.
        """
        raise NotImplementedError

    def prepare_rename(self, renames):
        """[(адрес, новое имя)] -> `Plan`. Ничего не пишет."""
        raise NotImplementedError

    def read_form(self, owner, name):
        """Что уже есть в форме — `domain.forms.FormView`; `None` — формы нет.

        `owner` — пара (вид, имя) хозяина, `None` — общая форма.
        """
        raise NotImplementedError

    def form_files(self, owner, name):
        """Где лежит форма: (файл описания, файл модуля или `None`).

        Для показа: человек должен видеть, какой файл перед ним, не выводя
        путь по правилам выгрузки сам. Путь здесь — данные для текста, а не
        приглашение читать файл в обход площадки.
        """
        raise NotImplementedError

    def prepare_form_edits(self, items, new_id):
        """[(правки формы, спецификация хозяина | None, uuid для новой формы)] -> `Plan`.

        Ничего не пишет. Как форма лежит в файлах и какой версией формата —
        дело площадки: сценарий отдаёт правки словами домена и способ получить
        идентификаторы, а обратно получает план.
        """
        raise NotImplementedError

    def render_form_code(self, edits, view=None, код_форм=None):
        """Правки формы -> (текст фрагмента кода для `ПриСозданииНаСервере`,
        [(область, имя, директива, параметры)] процедур-обработчиков).

        Второй выход из того же описания: своя форма правится в XML, типовая —
        только программно. `код_форм` — язык кода (`domain.conventions.КодФорм`):
        методы платформы или диалект команды. Вставку в модуль делает
        задание на код инструмента, с метками; здесь — текст и что положить в
        модуль формы.
        """
        raise NotImplementedError

    def handler_signatures(self, edits):
        """[(имя процедуры, директива, параметры)] обработчиков задания — с
        сигнатурами корпуса; параметры `None` — сигнатура не замерена. По ним
        сверяется процедура, которая в модуле формы уже есть."""
        return []


class ChangeSource:
    """Правки задачи: какие файлы изменены и как — против базы.

    Две реализации: git (рабочая копия или ревизия против базовой ревизии) и
    пара каталогов «эталон — копия» — обработка или отчёт вне репозитория.
    Сценарию достаются пути от корня выгрузки (через «/»), строки и байты;
    где лежат файлы, как их читать, что в выгрузке модуль, а что служебный
    файл, — знает площадка: выгрузка конфигуратора и проект EDT раскладывают
    файлы по-разному, и сценарий этой разницы не видит.
    """

    #: Как сравниваются версии: `GIT` — история репозитория, `PAIR` — два каталога.
    GIT, PAIR = "git", "пара каталогов"
    mode = GIT

    def describe(self):
        """Что с чем сравнивается — словами, для ответа."""
        raise NotImplementedError

    def changes(self):
        """[`domain.changes.FileChange`] — файлы задачи, по пути."""
        raise NotImplementedError

    def lines(self, path, side):
        """Строки файла версии `side` (`BEFORE`/`AFTER`) без переводов строк;
        файла в этой версии нет — None."""
        raise NotImplementedError

    def data(self, path, side):
        """Байты файла версии `side`; нет — None."""
        raise NotImplementedError

    def hunks(self, path):
        """[`domain.changes.Hunk`] — участки различий файла между версиями."""
        raise NotImplementedError

    def unchanged_pairs(self, path):
        """[(строка до, строка после)] — кандидаты «та же строка, другие пробелы»."""
        raise NotImplementedError

    def accepted_eol(self):
        """(«CRLF» | «LF» | None, пояснение): переводы строк, принятые там, где
        лежит выгрузка. None — сверять не с чем; пояснение — почему."""
        raise NotImplementedError

    def format_notes(self):
        """[пояснение] — правила, которые к формату исходников не применимы: в
        проекте EDT нет служебного файла, который пересобирает платформа.
        Неприменимое — не «пропущено»: правило не смотрело мимо, ему не на что
        смотреть, и вердикт от него не становится неполным."""
        return []

    def accepted_bom(self):
        """BOM, принятый там, где лежат исходники: True — текстовые файлы с BOM
        (выгрузка конфигуратора), False — без (проект EDT)."""
        raise NotImplementedError

    def is_module(self, path):
        """Файл — модуль кода."""
        raise NotImplementedError

    def is_text(self, path):
        """Файл — текстовый файл выгрузки (BOM, переводы строк, пробелы)."""
        raise NotImplementedError

    def is_service(self, path):
        """Служебный файл выгрузки, который пересобирает платформа."""
        raise NotImplementedError

    def object_of(self, path):
        """(вид, имя), если файл — карточка объекта метаданных; иначе None."""
        raise NotImplementedError

    def owner_of(self, path):
        """(вид, имя) объекта, которому принадлежит файл: карточка и всё, что
        лежит при объекте, — модули, формы, макеты, права; иначе None."""
        raise NotImplementedError

    def card_path(self, kind, name):
        """Путь карточки объекта; вид, которого выгрузка не знает, — None."""
        raise NotImplementedError

    def composition(self, kind, name, side):
        """Состав объекта в версии `side` — `domain.plan.Состав`; карточки в этой
        версии нет — None. Карточка, которая не читается, — состав с причиной."""
        raise NotImplementedError

    def module_of(self, path):
        """(вид, имя, модуль), если файл — собственный модуль объекта (модуль
        объекта, менеджера, набора записей, общий модуль); иначе None."""
        raise NotImplementedError

    def module_path(self, kind, name, module):
        """Путь собственного модуля объекта; у вида таких модулей не бывает — None."""
        raise NotImplementedError

    def roles_granting(self, objects):
        """{(вид, имя): [(роль, включено ли право)]} — роли новой версии, где
        объект назван; None — ролей в этом источнике нет (обработка вне
        конфигурации)."""
        raise NotImplementedError

    def target_eol(self, path):
        """Переводы строк, к которым приводить файл: «CRLF», «LF» или None —
        свои переводы файла (сверять не с чем)."""
        raise NotImplementedError

    def target_bom(self, path):
        """Нужен ли файлу BOM: True или False."""
        raise NotImplementedError

    def prepare_rewrites(self, items):
        """[(путь, байты)] -> `Plan` перезаписи файлов новой версии. Ничего не
        пишет; ревизию переписать нельзя — отказ."""
        raise NotImplementedError


class KindReference:
    """Что формат знает о видах — для справки, без выгрузки.

    Справка печатается по живым описаниям, чтобы не разъехаться с кодом. Часть
    этих описаний — чья-то перекладка на слова выгрузки (словари значений,
    самостоятельность вида), и каналу за ней в `acl` ходить нельзя: получает
    через этот договор.
    """

    def standalone(self, kind_name):
        """Заводится ли вид самостоятельным объектом со своей карточкой."""
        raise NotImplementedError

    def dictionaries(self, kind_name):
        """{поле: [допустимые слова]} — у полей, значения которых из словаря."""
        raise NotImplementedError


class Modules:
    """Модули кода в выгрузке — для правки вставками.

    Ссылка на модуль (`domain.modules.ModuleRef`) для сценария непрозрачна:
    как из адреса или пути получается файл, в какой кодировке он лежит, какими
    переводами строк и с BOM ли, — знает площадка. Сценарию достаются строки.
    """

    def read(self, ref):
        """Строки модуля без переводов строк. Модуля нет — `Refuse` с подсказкой."""
        raise NotImplementedError

    def address(self, ref):
        """Адрес модуля по метаданным (`ModuleAddress`) — и у названного путём;
        путь вне шаблонов выгрузки — None."""
        raise NotImplementedError

    def base(self, ref, rev=None):
        """Строки модуля в базовой версии — до правок задачи; нет её — None.
        `rev` — ревизия до задачи; `None` — `HEAD`.

        По ней откат сверяет пустые строки на стыках снятых вставок: отличить
        разделитель от пустой строки, бывшей в модуле, по тексту нельзя.
        """
        raise NotImplementedError

    def is_new(self, ref, rev=None):
        """Создан ли модуль текущей задачей: в ревизии до задачи (`rev`,
        `None` — `HEAD`) его нет.

        От этого зависит, нужна ли разметка вообще: внутри модуля, созданного
        задачей, меток нет.
        """
        raise NotImplementedError

    def prepare(self, changes):
        """[(ссылка, новые строки)] -> `Plan`. Ничего не пишет; формат файла
        (кодировка, BOM, переводы строк) сохраняется таким, каким был."""
        raise NotImplementedError

    def file_format(self, ref):
        """Формат прочитанного модуля словами — «CRLF, BOM» — или None: модуль
        не читался. Ответ называет его, чтобы сохранность формата была видна
        без побайтной проверки: grep в Git Bash отбрасывает CR, и сохранённый
        CRLF легко принять за переписанный LF."""
        return None
