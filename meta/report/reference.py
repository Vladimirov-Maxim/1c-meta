def overview(kinds, подсказки=БЕЗ_КАНАЛА):
    """Операции и виды: [(имя, описание вида, самостоятельный)] -> строки.

    Списки разные, потому что и операции разные: самостоятельный объект
    заводится ключом `objects` и получает свою карточку, вложенный — ключом
    `additions` по адресу хозяина. Одним списком это читалось бы как
    «создаётся всё», хотя половина видов отдельно не создаётся никогда.
    """
    строки = []
    пиши = строки.append
    standalone, nested = [], []
    for name, kind, самостоятельный in kinds:
        children = ", ".join(f for f, _ in kind.child_fields)
        line = "   {:22} {}".format(name, "с содержимым: " + children if children else "")
        (standalone if самостоятельный else nested).append(line)
    пиши("Операции. В одном задании — что-то одно; значение операции — список пунктов:\n")
    for ключ, что, пункт in OPERATIONS:
        if ключ == "forms" and подсказки.формы:
            continue
        пиши(f"   {ключ:12} {что}")
        пиши(f"   {'':12} пункт: {пункт}")
    if подсказки.формы:
        пиши(f"\n{подсказки.формы}")
    пиши("\nСамостоятельные объекты — заводятся ключом «objects»:\n")
    пиши("\n".join(standalone))
    пиши("\nВложенные — добавляются ключом «additions» по адресу хозяина:\n")
    пиши("\n".join(nested))
    # Про макет со схемой сказано отдельно: иначе отчёт заводят пустым, а
    # схему потом ищут, чем добавить. Это единственное место, где объект
    # создаётся не один, а сразу с файлами рядом.
    пиши("\nУ отчёта поле «схема» заводит макет со схемой компоновки "
         "сразу:\n   объект, карточка макета и пустая схема в нём — "
         "одним заданием.\n   Дальше в схему добавляют наборы, параметры "
         "и пункты настроек\n   ключом «additions» по адресу "
         "«Отчет.Имя.Макет.Схема».")
    строки.extend(подсказки.подвал_обзора)
    return строки


def types():
    """Справка по описанию типа.

    Без неё подключи (`фиксированная` и прочие) узнавали бы только отказом,
    а цена ошибки здесь выше обычной — не тот ключ молча дал бы
    `Число(10.2)` вместо `Число(15.2)`.
    """
    строки = []
    пиши = строки.append
    # Краткая запись — первой: ею тип печатает просмотр, и её принимают оба
    # задания.
    пиши("Тип пишется краткой записью — так его печатает show — или объектом.\n")
    пиши("Краткая запись:")
    пиши("   Строка(50)  Строка(9, фиксированная)  Число(15,2)  Число(10,0, неотрицательное)")
    пиши("   Дата (только дата)  ДатаВремя  Время  Булево  ХранилищеЗначения  …")
    пиши("   Справочник.Контрагенты — ссылка;  Документ.Заявка (Объект) — с гранью;  "
         "Справочник.* — весь вид")
    пиши("   ОпределяемыйТип.ДенежнаяСумма  Характеристика.ВидыСубконто  ЛюбаяСсылка")
    пиши("   составной — через «|»: «Строка(10) | Справочник.Склады»")
    пиши("\nОбъектом — ключ «вид» обязателен всегда:")
    for вид, ключи in TYPE_KEYS.items():
        подключи = ", ".join(к for к in ключи if к != "вид") or "(других нет)"
        обяз = QUALIFIER_KEY.get(вид)
        строка = f"   {вид:18} {подключи}"
        if обяз:
            строка += f"   — «{обяз}» обязателен"
        пиши(строка)
        # Список допустимых значений инструмент знает и печатает в отказе —
        # нужен он и там, куда смотрят ДО запуска.
        for (свой, поле), значения in QUALIFIER_VALUES.items():
            if свой == вид:
                пиши(f"   {'':18} {поле}: {', '.join(значения)}")
    пиши("\nСсылка на объект:  вид, имя, грань "
         "(грань «Ссылка» подразумевается)")
    пиши("   например: {\"вид\": \"Справочник\", \"имя\": \"Контрагенты\"}")
    пиши("\nБез квалификатора (пишутся одним «видом»):")
    пиши("   " + ", ".join(PLATFORM_KINDS))
    пиши("\nПримеры объектом:")
    for вид, пример in EXAMPLE.items():
        пиши(f"   {вид:18} {пример}")
    пиши('   Булево             {"вид": "Булево"}')
    пиши("\nСоставной объектом — список: [{\"вид\": \"Строка\", \"длина\": 10}, "
         "{\"вид\": \"Справочник\", \"имя\": \"Склады\"}]")
    return строки


def is_a_type_word(name):
    """Про типы спрашивают как про вид — и получали бы отказ со списком видов,
    в котором типа нет и быть не может."""
    return name in ("Тип", "Типы") or name in TYPE_KEYS or name in PLATFORM_KINDS


