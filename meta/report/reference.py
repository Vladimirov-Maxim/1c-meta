def kind_fields(kind_name, kind, dictionaries):
    """Поля вида: обязательные, допустимые значения, умолчания, особая запись."""
    строки = []
    пиши = строки.append
    children = dict(kind.child_fields)
    # Вычисляемые поля названы: просмотр считает «ещё N полей» без них, и
    # иначе счёт не сошёлся бы со справкой. Только те, что у вида есть:
    # перечень общий для всех видов, а табличной части или отбору таких полей
    # не дано.
    вычисляемые = tuple(f for f in (getattr(kind, "derived", ()) or ())
                        if f in kind.fields)
    пиши(f"{kind_name}: полей {len(kind.fields)}, "
         f"обязательные — {', '.join(kind.required)}"
         + (f"; вычисляет инструмент — {', '.join(вычисляемые)}: по виду объекта и типу, "
            "как ставит конфигуратор (что решено — показ с подробностями)"
            if вычисляемые else "") + "\n")
    for field in kind.fields:
        note = ""
        if field in children:
            # «Описывается так же, как объект» толкало бы обернуть ребёнка
            # в «вид»/«поля» — так выглядит объект в задании. Ребёнок пишется
            # полями напрямую, и сказано именно это.
            note = (f"список: {children[field]} — полями напрямую, "
                    'без "вид"/"поля"')
        elif (kind_name, field) in SHAPED_BY_KIND:
            note = SHAPED_BY_KIND[(kind_name, field)]
        elif field in SHAPED:
            note = SHAPED[field]
        else:
            # Словарь и умолчание — разные сведения, и печатать нужно оба:
            # по одному списку (у «видИерархии», у «повторного использования»)
            # из справки не следует, что будет, если поле не назвать.
            куски = []
            if field in dictionaries:
                куски.append("допустимо: " + ", ".join(dictionaries[field]))
            if field in kind.defaults:
                куски.append(f"по умолчанию: {kind.defaults[field]!r}")
            note = "; ".join(куски)
        пиши(f"   {field:32} {note}")
    if kind_name in atomic_kinds():
        # Поле задания, а не карточки: в списке полей вида его нет, поэтому
        # оно названо отдельно — иначе его искали бы там.
        пиши(f"   {'атомарныеРоли':32} {SHAPED['атомарныеРоли']} — поле задания, "
             "в карточку не пишется")
    if kind_name == "ОбщийМодуль":
        # Умолчания контекстов печатаются как у серверного модуля, а у модуля
        # с вызовом сервера они другие — без этой строки справка обещала бы
        # «внешнееСоединение: True» тому, кто получит False.
        пиши("\nКонтекст задаёт постфикс имени — стандарт #469; доли — по 4103 модулям "
             "замеренной конфигурации:\n"
             "   (нет) или Сервер   — сервер + внешнееСоединение + клиентОбычноеПриложение\n"
             "   ВызовСервера       — сервер + вызовСервера              (439 из 455)\n"
             "   Клиент             — оба клиента                         (631 из 636)\n"
             "   КлиентСервер       — все четыре контекста                (466 из 475)\n"
             "   Глобальный         — глобальный + оба клиента            (56 из 58)\n"
             "   …ПовтИсп           — плюс повторное использование НаВремяСеанса (205 из 222)\n"
             "   …ПолныеПрава       — плюс привилегированный\n"
             "Названное явно не трогается. Имя и флаги обязаны сходиться: «вызов сервера»\n"
             "без постфикса ВызовСервера, «глобальный» без Глобальный, Клиент без клиента —\n"
             "отказ; отклонение состава контекстов от стандарта — предупреждение.")
    if kind_name == "ПодпискаНаСобытие":
        # Число параметров обработчика проверяется — но на следующем задании,
        # когда модуль уже записан, а метод в существующий модуль дописывает
        # только задание на код. Знание нужно раньше, чем срабатывает проверка.
        пиши("\nСколько параметров у обработчика (по 639 подпискам замеренной конфигурации):\n")
        for (событие, вид, грань), (сколько, так, всего) in sorted(HANDLER_ARITY.items()):
            пиши(f"   {событие:22} {вид + ' (' + грань + ')':34} "
                 f"{сколько} — так у {так} из {всего}")
    if kind_name == "Роль":
        # У вида бывают не все 70 прав, и инструмент это проверяет — значит
        # и показать обязан здесь, а не только в отказе.
        пиши("\nПрава по видам (по 2709 ролям замеренной конфигурации):\n")
        for вид in sorted(RIGHTS_BY_KIND):
            пиши(f"   {вид:32} {', '.join(sorted(RIGHTS_BY_KIND[вид]))}")
    return строки
