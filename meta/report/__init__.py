"""Язык ответов: результат сценария -> строки текста для человека или агента.

Оба канала — терминал и MCP — отвечают одним и тем же текстом: сообщения об
ошибках и планы не должны жить двумя жизнями. Поэтому рендеринг лежит под
каналами, а не в одном из них.

Одно в тексте принадлежит каналу, а не ответу: как сказать «сделай ещё
что-то». У терминала это ключи (`--поля Вид`, `--apply`), у MCP — вызовы
инструментов. Такие подсказки канал передаёт сам, объектом `Подсказки`; язык
ответов своих ключей не знает.

Функции возвращают список строк вывода. Канал печатает их по одному или
склеивает переводом строки — вывод выходит один и тот же.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Подсказки:
    """Слова канала для подсказок в ответе.

    `поля` — шаблон с `{вид}`: где смотреть поля вида. `записать` — чем
    повторить просмотр с записью. `подробно` — как показать спрятанное.
    `подвал_обзора` — последние строки обзора видов: как спросить поля, тип,
    что лежит в выгрузке. `код` — чем внести код в модуль с метками —
    словом этого канала.
    `ключ_модуля` — как модуль называется в задании на код: у MCP ключи
    латиницей («module»), у терминала — «модуль». `формы` — как в этом канале
    даются формы, если не ключом «forms» того же задания: у MCP это свои
    инструменты, и обзор операций не числит формы рядом с objects.
    `ветвь` — как показ формы сужают до одной ветки: у MCP параметр, у
    терминала третий аргумент.
    """

    поля: str
    записать: str
    подробно: str
    подвал_обзора: tuple = ()
    код: str = "заданием на код этого же инструмента"
    ключ_модуля: str = "модуль"
    формы: str = None
    ветвь: str = "имени элемента"


#: Нейтральные подсказки — для вызова мимо канала (тесты рендеринга): ответ
#: без отсылок к ключам, но с тем же составом.
БЕЗ_КАНАЛА = Подсказки(поля="справку по виду {вид}", записать="запишите",
                       подробно="подробный показ")
