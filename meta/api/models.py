"""Модель запроса MCP: задания на форму и на код, описанные типами.

Это тот же формат, что в файле задания для терминала, — те же ключи, та же
вложенность, — только описанный типами. Из типов сервер строит схему
инструмента, и агент получает формат задания от самого сервера, а не из
README.

Лишние ключи модель пропускает намеренно (`extra="allow"`): отказ по ним даёт
язык заданий — по-русски и с перечнем допустимых, — а не валидатор транспорта
по-английски. Модель описывает форму запроса; судит его язык заданий.

**Имена классов — латиницей, русское имя — в `title`.** Имя класса становится
ключом в `$defs` схемы, а клиент заменяет в таких ключах кириллицу
подчёркиваниями: «ПравкаКода» и «МодульКода» одной длины превращаются в одну
и ту же строку, и различает их только случайная приставка. Ключи верхнего
уровня параметров инструмента обязаны быть латиницей по той же причине, только
строже: иначе API отвергает схему, и инструмент молча выпадает из сессии —
например, с параметром «принято». Русские ключи **внутри** моделей — ключи
самого языка заданий — проходят и остаются русскими.
"""

from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from ..domain.model import Refuse


def _config(title, **extra):
    """Лишние ключи модель пропускает — их судит язык заданий, по-русски, — а
    схема объявляет их недопустимыми: так схема совпадает с поведением и не
    разрешает того, что инструмент отвергает."""
    return ConfigDict(extra="allow", title=title,
                      json_schema_extra={"additionalProperties": False}, **extra)


