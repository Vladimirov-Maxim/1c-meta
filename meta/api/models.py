class CodeEdit(_Model):
    model_config = _config("ПравкаКода")

    # Что такое якорь у замены и куда якорить новый метод — словами схемы,
    # а не выводом из соседних полей.
    line: int = Field(description="строка-якорь, с единицы: у замены — первая заменяемая "
                                  "строка, у вставки (lines = 0) — строка, перед которой "
                                  "встанет код; новый метод в конец области — якорем её "
                                  "#КонецОбласти. Номер — из текущего текста файла ДО задания "
                                  "(правки одного задания друг друга не сдвигают), никогда "
                                  "не из устаревшей копии или поискового индекса")
    lines: int = Field(0, description="сколько строк заменяется; 0 — вставка перед якорем")
    first_line: str | None = Field(None, description="точный текст первой заменяемой строки, "
                                                     "с ведущими табуляциями (хвостовые пробелы "
                                                     "не сверяются): обязателен при lines > 0; "
                                                     "при lines = 0 схема его не требует, но "
                                                     "передавайте — он сверяется со "
                                                     "строкой-якорем, без него устаревший номер "
                                                     "не ловится")
    last_line: str | None = Field(None, description="точный текст последней заменяемой строки "
                                                    "(обязателен при lines > 0)")
    # Сказано точно: «отступ можно не набирать» читается шире, чем есть, а
    # «новый метод — с описанием» — как требование описывать любой метод.
    code: str = Field("", description="новый код без меток — их ставит инструмент; блок, "
                                      "пришедший мельче места правки, сдвигается на его уровень "
                                      "целиком (перед КонецПроцедуры, КонецЕсли, Иначе — внутрь "
                                      "конструкции), отступы внутри кода — ваши; описание метода, "
                                      "если оно есть, — в том же коде над методом (метка встанет "
                                      "над описанием); новая область — целиком с #Область/"
                                      "#КонецОбласти (их метки не оборачивают, каждый метод "
                                      "получает свою); пустой — удаление")


class MethodRename(_Model):
    model_config = _config("Переименование", populate_by_name=True)

    from_: str = Field(alias="from", description="имя метода, объявленного в этом модуле")
    to: str = Field(description="новое имя")


# Ключи — латиницей, как у `path`, `edits`, `line`: смесь «модуль» с латинскими
# соседями сбивает. Язык заданий терминала зовёт его «модуль» — переводит
# контроллер. Комментарием, а не описанием класса: описание уходит в схему, и
# служебная пометка шумела бы в описании модели.
class CodeModule(_Model):
    model_config = _config("МодульКода")

    module: str | None = Field(None, description="адрес, как у bsl-ls: ОбщийМодуль.мой_X, "
                                                 "Документ.мой_Заявка.МодульОбъекта, "
                                                 "Документ.X.Форма.ФормаДокумента, "
                                                 "Документ.X.Команда.Печать")
    path: str | None = Field(None, description="путь файла относительно repo, через «/» — "
                                               "вместо адреса, ровно одно из двух")
    edits: list[CodeEdit] | None = None
    revert: bool | None = Field(None, description="снять вставки этой задачи в модуле; пустые "
                                                  "строки на стыках сверяются с версией в HEAD "
                                                  "(нет модуля в HEAD или задача закоммичена — "
                                                  "не сверяются, ответ это говорит)")
    # Сказано прямо, что внешних вызывающих инструмент не ищет и что метка на
    # объявлении превращает переименование в копию метода: иначе первое стало бы
    # ясно только из ответа, второе — из общего описания code_check.
    rename: MethodRename | None = Field(None, description="переименовать метод, объявленный в "
                                                          "модуле: объявление и обращения внутри "
                                                          "этого модуля. Если на объявлении стоит "
                                                          "чужая метка (вставка — весь метод), "
                                                          "правка объявления оборачивает весь "
                                                          "метод: в модуле окажутся его "
                                                          "закомментированная копия и новый метод "
                                                          "целиком. Вызовы из других модулей "
                                                          "(Модуль.Метод) инструмент не ищет и не "
                                                          "правит — найдите их поиском по "
                                                          "каталогам модулей выгрузки "
                                                          "(CommonModules, Documents…) и внесите "
                                                          "обычными правками")


