def _no_duplicates(pairs):
    """Повторённый ключ в задании — отказ, а не «выигрывает последний».

    JSON молча берёт последнее значение. Для поля `repo` это значит, что
    задание с двумя путями запишет по второму, ничего не сказав, — а первый
    человек и считает настоящим, потому что видит его первым.
    """
    seen = {}
    for key, value in pairs:
        if key in seen:
            raise ValueError(f"ключ «{key}» указан дважды; какое из значений "
                             "верное, инструмент не угадывает")
        seen[key] = value
    return seen


def _code_path(job, job_path, адрес):
    """Куда лечь фрагменту кода: сказанное в задании или рядом с ним.

    Файл, а не буфер: текст идёт в задание на код, а оно берёт вставку
    из файла, который человек собирает рядом.
    """
    сказано = job.get("файлКода")
    if сказано:
        return сказано if os.path.isabs(сказано) else os.path.join(
            os.path.dirname(os.path.abspath(job_path)), сказано)
    имя = адрес.replace(".", "_") + ".bsl"
    return os.path.join(os.path.dirname(os.path.abspath(job_path)), имя)


def show(controller, repo, address, подробно=False, ветвь=None):
    """`--показать`: объект или форма из выгрузки; у формы — третьим
    аргументом имя элемента, чтобы показать только его ветку."""
    if not os.path.isdir(repo):
        print(f"ОТКАЗ: каталога «{repo}» не существует")
        return 2
    try:
        ответ = controller.show(repo, address)
    except Refuse as отказ:
        print(f"ОТКАЗ: {отказ}")
        return 1
    if ответ[0] == "форма":
        _, view, name, form_file, module_file, своя = ответ
        печать(shown_form(view, name, form_file, module_file, подробно, ПОДСКАЗКИ, ветвь=ветвь,
                          своя=своя))
    else:
        _, spec, файл = ответ
        печать(shown_object(spec, файл, ПОДСКАЗКИ))
        if ветвь:
            print("третий аргумент — ветка дерева формы; у объекта не применяется")
    return 0


def fields(controller, kind_name=None):
    """`--поля`: обзор видов, поля вида, свойства элемента формы или описание типа."""
    if not kind_name:
        печать(overview(controller.kinds(), ПОДСКАЗКИ))
        return 0
    if kind_name in ("Тип", "Типы"):
        печать(types())
        return 0
    if kind_name in CODE_WORDS:
        печать(code_rules(ПОДСКАЗКИ))
        return 0
    found = controller.kind(kind_name)
    if found is not None:
        печать(kind_fields(kind_name, *found))
        return 0
    свойства = element_properties(kind_name)
    if свойства is not None:
        печать(свойства)
        return 0
    if is_a_type_word(kind_name):
        печать(types())
        return 0
    print("вида «{}» нет; есть: {}".format(kind_name, ", ".join(controller.kind_names())))
    return 2


def _разобрать(argv, команда, со_значением):
    """argv -> (позиционные, {ключ: значение}). Неизвестный ключ и ключ без
    значения — отказ: молча проглоченный ключ сменил бы предмет проверки."""
    позиционные, значения, i = [], {}, 0
    while i < len(argv):
        слово = argv[i]
        if слово == команда:
            i += 1
        elif слово in со_значением:
            if i + 1 >= len(argv) or argv[i + 1].startswith("--"):
                raise Refuse(f"{слово}: после ключа нужно значение")
            значения[слово] = argv[i + 1]
            i += 2
        elif слово.startswith("-"):
            raise Refuse(f"{команда}: не знаю ключа {слово}; известны: {', '.join(со_значением)}")
        else:
            позиционные.append(слово)
            i += 1
    return позиционные, значения


def verify(controller, argv):
    """`--проверить`: правки задачи против базы; код 2 — ошибка входа, а не «чисто»."""
    try:
        позиционные, ключи = _разобрать(argv, "--проверить", КЛЮЧИ_ПРОВЕРКИ)
        if len(позиционные) > 1:
            raise Refuse(f"выгрузка одна, получено: {', '.join(позиционные)}")
        только = [код.strip() for код in (ключи.get("--только") or "").split(",") if код.strip()]
        result = controller.verify(repo=позиционные[0] if позиционные else None,
                                   base=ключи.get("--база", "HEAD"), rev=ключи.get("--ревизия"),
                                   baseline=ключи.get("--эталон"), target=ключи.get("--копия"),
                                   task=ключи.get("--задача"), only=только)
    except Refuse as отказ:
        print(f"ОТКАЗ: {отказ}")
        return 2
    печать(verify_lines(result))
    if ключи.get("--json"):
        with open(ключи["--json"], "w", encoding="utf-8", newline="\n") as файл:
            json.dump(verify_json(result), файл, ensure_ascii=False, indent=1)
    return 0 if result.ok else 1


def normalize(controller, argv):
    """`--нормализовать`: просмотр, с `--apply` — запись; код 1 в просмотре —
    есть что исправить, 2 — ошибка входа."""
    apply_now = "--apply" in argv
    try:
        позиционные, ключи = _разобрать([a for a in argv if a != "--apply"], "--нормализовать",
                                        КЛЮЧИ_НОРМАЛИЗАЦИИ)
        if len(позиционные) > 1:
            raise Refuse(f"выгрузка одна, получено: {', '.join(позиционные)}")
        result = controller.normalize(repo=позиционные[0] if позиционные else None,
                                      base=ключи.get("--база", "HEAD"), baseline=ключи.get("--эталон"),
                                      target=ключи.get("--копия"), apply_now=apply_now)
    except Refuse as отказ:
        print(f"ОТКАЗ: {отказ}")
        return 2
    печать(normalize_lines(result, apply_now, "повторите с --apply"))
    return 0 if apply_now or result.ok else 1


def _источник(позиционные, ключи):
    """Источник правок из ключей: выгрузка позиционно или пара «эталон — копия»."""
    if len(позиционные) > 1:
        raise Refuse(f"выгрузка одна, получено: {', '.join(позиционные)}")
    return dict(repo=позиционные[0] if позиционные else None, base=ключи.get("--база", "HEAD"),
                rev=ключи.get("--ревизия"), baseline=ключи.get("--эталон"), target=ключи.get("--копия"))


def plan_check(controller, argv):
    """`--сверить-план`: план JSON-файлом против факта задачи; код 2 — ошибка входа."""
    try:
        позиционные, ключи = _разобрать(argv, "--сверить-план", КЛЮЧИ_ПЛАНА)
        if not ключи.get("--план"):
            raise Refuse("--план <файл.json>: план изменений — JSON с ключом «объекты»")
        try:
            with open(ключи["--план"], encoding="utf-8-sig") as файл:
                план = файл.read()
        except OSError as ошибка:
            raise Refuse(f"план «{ключи['--план']}» не прочитан: {ошибка}") from ошибка
        result = controller.plan_check(план, **_источник(позиционные, ключи))
    except Refuse as отказ:
        print(f"ОТКАЗ: {отказ}")
        return 2
    печать(plan_check_lines(result))
    if ключи.get("--json"):
        with open(ключи["--json"], "w", encoding="utf-8", newline="\n") as файл:
            json.dump(plan_check_json(result), файл, ensure_ascii=False, indent=1)
    return 0 if result.ok else 1


def plan_emit(controller, argv):
    """`--план-по-факту`: факт задачи планом — JSON в вывод (и файлом с `--json`)."""
    try:
        позиционные, ключи = _разобрать(argv, "--план-по-факту", КЛЮЧИ_ФАКТА)
        result = controller.plan_emit(**_источник(позиционные, ключи))
    except Refuse as отказ:
        print(f"ОТКАЗ: {отказ}")
        return 2
    текст = json.dumps(plan_emit_json(result), ensure_ascii=False, indent=1)
    print(текст)
    if ключи.get("--json"):
        with open(ключи["--json"], "w", encoding="utf-8", newline="\n") as файл:
            файл.write(текст + "\n")
    return 0


def main(argv, controller):
    """Терминал: ключи и файл задания -> контроллер -> текст."""
    if "--проверить" in argv:
        return verify(controller, argv)
    if "--нормализовать" in argv:
        return normalize(controller, argv)
    if "--сверить-план" in argv:
        return plan_check(controller, argv)
    if "--план-по-факту" in argv:
        return plan_emit(controller, argv)
    flags = [item for item in argv if item.startswith("-")]
    rest = [item for item in argv if not item.startswith("-")]
    if "--показать" in flags:
        if len(rest) not in (2, 3):
            print("--показать <путь к выгрузке> <адрес> [<элемент формы>]\n"
                  "   объект: --показать C:/cf Справочник.мой_Эталон\n"
                  "   форма:  --показать C:/cf Документ.мой_Заявка.ФормаДокумента\n"
                  "   ветка:  --показать C:/cf Документ.мой_Заявка.ФормаДокумента ГруппаШапка")
            return 2
        return show(controller, rest[0], rest[1], "--подробно" in flags,
                    rest[2] if len(rest) == 3 else None)
    if set(flags) & {"-h", "--help"}:
        print(__doc__)
        return 0                          # спросили справку — это не падение
    if not argv:
        print(__doc__)
        return 2
    # Порядок слов не значит ничего: иначе `add.py --apply job.json` читался
    # бы как «задание лежит в файле --apply» и падал трассировкой.
    unknown = [flag for flag in flags if flag not in КЛЮЧИ]
    if unknown:
        print("не знаю ключей: {}; известны: {}".format(
            ", ".join(unknown), ", ".join(КЛЮЧИ)))
        return 2
    if "--поля" in flags:
        return fields(controller, rest[0] if rest else None)
    if not rest:
        print("не указан файл задания")
        return 2
    job_path = rest[0]
    apply_now = "--apply" in flags
    try:
        source = open(job_path, encoding="utf-8-sig").read()
    except OSError as failure:
        raise Refuse(
            f"файл задания «{job_path}» не читается: {failure.strerror}"
        ) from failure
    except UnicodeDecodeError as failure:
        # Блокнот сохраняет в кодировку системы, и на Windows это будничный
        # случай: стек Python здесь был бы чужим в инструменте, который
        # всюду говорит по-русски и по делу.
        raise Refuse(
            f"файл задания «{job_path}» не в UTF-8 (сломалось на байте "
            f"{failure.start}). Пересохраните в UTF-8: в Блокноте это "
            "«Файл → Сохранить как → Кодировка: UTF-8»") from failure
    try:
        job = json.loads(source, object_pairs_hook=_no_duplicates)
    except ValueError as failure:
        raise Refuse(
            f"в задании «{job_path}» испорчен JSON: {failure}") from failure

    # Путь печатается до всего остального. Он виден и в плане, но внутри
    # длинных абсолютных строк: укажи человек по ошибке соседнюю выгрузку,
    # вывод выглядел бы точно так же успешно.
    print(f"Выгрузка: {families.repo_of(job)}")
    result = controller.execute(job, apply_now)
    if isinstance(result, CodeResult):
        печать(code_lines(result, apply_now, ПОДСКАЗКИ, целиком="--подробно" in flags))
        return 0

    # Фрагмент кода для типовой формы терминал кладёт файлом рядом с
    # заданием: оттуда его берёт задание на код.
    куда_код = {}
    if result.ok:
        for адрес, текст in (getattr(result, "code", None) or {}).items():
            путь = _code_path(job, job_path, адрес)
            if apply_now:
                with open(путь, "w", encoding="utf-8-sig", newline="\r\n") as файл:
                    файл.write(текст)
                куда_код[адрес] = f"\nЗаписан фрагмент: {путь}"
            else:
                куда_код[адрес] = f"\nПросмотр: с --apply фрагмент ляжет в {путь}"
    # Подробный просмотр — и все поля, и тексты файлов: размер в плане не
    # говорит, что окажется в файле.
    печать(result_lines(result, принято=job.get("принято"),
                        подробно="--подробно" in flags, apply_now=apply_now,
                        подсказки=ПОДСКАЗКИ, куда_код=куда_код,
                        файлы="--подробно" in flags))
    return 0 if result.ok else 1
