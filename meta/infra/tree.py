"""Договор разбора и сборки карточки — внутренний шов инфраструктуры.

Здесь, а не в прикладном слое: ни один сценарий дерева не видит и ни
одного метода отсюда не вызывает. Прикладному слою нужны `Plan`
и `Platform`, и они в `application/ports.py`.

Замена библиотеки XML — новая реализация этого договора рядом
с `tree_lxml.py` и передача её в `Repository`.
"""


class CardTree:
    """Разбор карточки в дерево и сборка обратно.

    Договор лежит здесь, а реализация снаружи, ровно затем, чтобы конкретную
    библиотеку XML можно было заменить, не трогая сценарии. Дерево для
    приложения непрозрачно: что именно вернул `parse`, знает только реализация,
    а сценарий отдаёт это обратно в её же методы и внутрь не заглядывает.
    Тип дерева не должен покидать инфраструктуру — это стережёт гард
    в `tests/test_architecture.py`.

    Требование к реализации одно, и оно жёсткое:

        serialize(parse(текст)) == текст

    символ в символ, включая порядок атрибутов, форму пустого тега `<Тег/>`,
    экранирование `>`, которого XML не требует, и отступы табуляцией.
    Инструмент правит чужие файлы: всё, чего он не менял, обязано остаться
    нетронутым, иначе безобидная правка одного свойства даст diff, неотличимый
    от переписывания файла целиком. Это не пожелание, а то, что проверяется
    на всей выгрузке крупной типовой конфигурации.
    """

    def parse(self, text):
        """Текст карточки (с объявлением XML, переводы строк `\\n`) -> дерево."""
        raise NotImplementedError

    def serialize(self, tree):
        """Дерево -> текст карточки. Обратное `parse` символ в символ."""
        raise NotImplementedError

    def granted(self, tree):
        """Дерево файла прав роли -> [(объект словом файла, [выданные права словом
        файла])] — только объекты, на которые выдано хоть одно право."""
        raise NotImplementedError

    def child_names(self, tree, element=None):
        """Имена детей: `child_names(дерево, "Attribute")` — заданного вида.

        Без вида — имена всех детей. Так спрашивают про занятость имени:
        у платформы имена детей объекта — одно пространство, реквизит и
        табличная часть с одним именем не сосуществуют. В замеренной выгрузке
        столкновений между видами детей нет ни одного на 7035 объектов.

        Только своих: в табличные части не спускается.
        """
        raise NotImplementedError

    def child_elements(self, tree):
        """Теги детей объекта по порядку: `["Attribute", "TabularSection"]`."""
        raise NotImplementedError

    def insert_child(self, tree, index, node):
        """Вставить описанный узел в раздел детей на указанное место."""
        raise NotImplementedError

    def child_elements_of(self, host):
        """Теги детей произвольного хозяина: табличной части, схемы, набора."""
        raise NotImplementedError

    def insert_child_of(self, host, index, node):
        """Вставить узел в раздел детей произвольного хозяина."""
        raise NotImplementedError

    def find(self, tree, path):
        """Путь `[("Attribute", "Код"), …]` -> узел. `None`, если не нашлось.

        Пустой путь — сам объект. Тот же механизм на любой глубине: реквизит
        объекта и реквизит его табличной части ищутся одинаково.

        Шаг без имени (`None`) — контейнер: в своём хозяине он один, и
        опознавать его нечем, кроме тега. Так проходятся неявные разделы
        настроек компоновки, которых в адресе никто не называет.
        """
        raise NotImplementedError

    def property_text(self, node, tag):
        """Текущее значение свойства как текст. `None` — свойства нет."""
        raise NotImplementedError

    def remove_child(self, tree, path):
        """Удалить вложенную сущность по пути. `False`, если её нет."""
        raise NotImplementedError

    def reference_places(self, tree, pattern):
        """Где в дереве стоят ссылки: `[(шаги, свойство)]` без повторов, по порядку.

        Шаги — сущности от объекта вглубь, тегами (с приставкой, как в файле:
        `dcsset:item`) и именами: `[("TabularSection", "Товары"), ("Attribute",
        "Склад")]`; пустые — ссылка в свойстве самого объекта. Свойство — тег
        без приставки у самой глубокой сущности (`Type`), `None` — если ссылка
        лежит вне её свойств.

        Ссылка — текст узла: тип реквизита, пункт состава, движение документа.
        Совпадение `pattern` в атрибуте или комментарии места не имеет и в ответ
        не попадает — вызывающий сам решает, чем такое назвать.
        """
        raise NotImplementedError

    def tag_of(self, node):
        """Имя тега узла без приставки пространства имён."""
        raise NotImplementedError

    def local_name(self, tag):
        """Тег, как его называет схема, -> имя без приставки.

        Обратная к тому, что делает сборка: схема называет теги так, как они
        стоят в файле (`dcsset:item`), а сравнивать их приходится с именами,
        которые вернул разбор. Приведение — дело реализации: только она знает,
        как записывает приставки.
        """
        raise NotImplementedError

    def child_by_tag(self, host, tag):
        """Прямой ребёнок хозяина с таким тегом. `None`, если его нет."""
        raise NotImplementedError

    def document(self, tree):
        """Чем документ является: `MetaDataObject`, `DataCompositionSchema`…

        От этого зависит порядок детей: у карточки он свой на каждый вид,
        у схемы компоновки — один на весь документ.
        """
        raise NotImplementedError

    def set_text(self, node, text):
        """Заменить текст узла, не трогая его места среди соседей.

        Нужно там, где сущность и есть свой текст: запись реестра
        конфигурации — это `<Catalog>Имя</Catalog>`, и переименование
        объекта здесь именно смена текста, а не перевставка узла.
        """
        raise NotImplementedError

    def set_property(self, node, tag, described):
        """Заменить свойство описанным узлом на месте. Вернуть прежний текст."""
        raise NotImplementedError

    def to_node(self, element):
        """Элемент дерева -> описание узла (`acl.Node`). Зеркало `build`.

        Нужно обратному чтению: карточка на диске превращается в те же узлы,
        из которых её собирала перекладка, а дальше перекладка переводит их
        на язык задания. Иначе чтение завело бы второе понимание формата —
        то самое, чего инструмент избегает у разбора.

        Приставки пространств имён снимаются: схема называет теги так же
        (`Name`, `v8:Type`), и сравнивать их с объявленными в схеме проще
        по короткому имени.
        """
        raise NotImplementedError

    def build(self, node):
        """Описание узла (`acl.Node`) -> дерево с проставленными отступами.

        Вход — описание из перекладки, а не строка: договор не знает ни тегов
        с префиксами, ни отступов, и другой реализации не пришлось бы разбирать
        чужой текст обратно.
        """
        raise NotImplementedError

    def render(self, node, level):
        """Узел -> текст на заданной глубине, без объявления и обёртки.

        Нужен там, где узел показывают отдельно от карточки: сверка с корпусом
        и просмотр. Записью это не пользуется — врезка вставляет узел в дерево,
        а не приклеивает строки к файлу.
        """
        raise NotImplementedError
